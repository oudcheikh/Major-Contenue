# -*- coding: utf-8 -*-
"""Narration U25 — الفواصل. Fidèle au cahier :
4 حالات : مغلق = · طرفان +1 · دون طرفين −1 · طرف واحد = ·
Le PIÈGE classique : 100 m، عمود كل 10 m وفي الطرفين ← 11 عمودًا (لا 10!).
Astuce du cahier : قبل أي حساب أرسم رسمًا صغيرًا: خط ونقاط."""
import asyncio, json, subprocess
from pathlib import Path

import edge_tts
import imageio_ffmpeg

VOICE = "ar-SA-HamedNeural"
RATE = "-3%"

SEGMENTS = [
    ("intro1", "أهلًا بكم يا أبطال الرياضيات! درسُ اليوم من الوحدة الخامسة والعشرين: الفواصل."),
    ("intro2", "في هذا الدرس سنتعلم عدّ الأشجار والأعمدة على الخطوط، "
               "وسنكتشف متى نزيد واحدًا ومتى لا نزيد."),
    # ── المفهوم ──
    ("def1", "عندما نغرس أشجارًا على طول طريق، فالمسافة بين كل شجرتين متجاورتين تسمى فاصلة."),
    # ── الفخ المشهور : 100 م، عمود كل 10 م ──
    ("piege1", "وإليكم السؤال المشهور: طريق مستقيمة طولها مائة متر، نضع عمودًا كل عشرة أمتار، "
               "وفي كل طرف عمود. كم عمودًا نحتاج؟"),
    ("piege2", "كثيرون يجيبون بسرعة: عشرة أعمدة! فهل هم على صواب؟"),
    ("piege3", "لنعدّ معًا عمودًا عمودًا: واحد، اثنان، ثلاثة، أربعة، خمسة، "
               "ستة، سبعة، ثمانية، تسعة، عشرة، أحد عشر!"),
    ("piege4", "أحد عشر عمودًا وليس عشرة! عدد الفواصل مائة على عشرة يساوي عشرة، "
               "لكن العمود الأول يقف عند الصفر قبل الفاصلة الأولى."),
    ("regle1", "القاعدة الأولى إذن: في الخط المفتوح إذا كان في كل طرف شيء، "
               "فعدد الأشياء يساوي عدد الفواصل زائد واحد."),
    # ── الخط المغلق : الدائرة ──
    ("cercle1", "والآن الخط المغلق: حول حديقة دائرية نضع ستة أعمدة، فكم فاصلة بينها؟"),
    ("cercle2", "لنعدّ الفواصل: واحدة، اثنتان، ثلاث، أربع، خمس، ست! "
                "في الدائرة آخر فاصلة تعود إلى العمود الأول، فعدد الأشياء يساوي عدد الفواصل تمامًا."),
    # ── الحالتان الأخريان ──
    ("cas1", "وبقيت حالتان: إذا خلا الطرفان من الأشياء فأنقص واحدًا، "
             "وإذا كان الشيء في طرف واحد فقط فالعددان متساويان."),
    # ── انتبه ──
    ("att1", "انتبه جيدًا! في الخط المغلق لا نزيد واحدًا أبدًا: "
             "عدد الأشياء يساوي عدد الفواصل تمامًا."),
    # ── السر ──
    ("astuce", "وقبل أن نفترق، إليكم سرًّا ذهبيًا: قبل أي حساب ارسم رسمًا صغيرًا: خط ونقاط! "
               "فالرسم يريك القاعدة الصحيحة فورًا."),
    ("outro", "والآن افتح كراسك وحلّ تمارين الوحدة الخامسة والعشرين. إلى اللقاء يا أبطال!"),
]

OUT = Path(__file__).parent / "audio_u25"


async def main():
    OUT.mkdir(exist_ok=True)
    ff = imageio_ffmpeg.get_ffmpeg_exe()
    durations = {}
    for name, text in SEGMENTS:
        mp3 = OUT / f"{name}.mp3"
        await edge_tts.Communicate(text, VOICE, rate=RATE).save(str(mp3))
        r = subprocess.run([ff, "-i", str(mp3), "-f", "null", "-"],
                           capture_output=True, text=True)
        for line in r.stderr.splitlines():
            if "time=" in line:
                t = line.split("time=")[1].split(" ")[0]
                h, m, s = t.split(":")
                durations[name] = round(int(h) * 3600 + int(m) * 60 + float(s), 2)
        print(f"{name}: {durations.get(name, '?')} s")
    (OUT / "durations.json").write_text(json.dumps(durations, indent=2))
    print("total:", round(sum(durations.values()), 1), "s")


if __name__ == "__main__":
    asyncio.run(main())
