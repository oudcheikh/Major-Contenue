# -*- coding: utf-8 -*-
"""Narration U11 — ضرب الكسور. Fidèle au cahier (unites_3.py u11) :
البسط × البسط والمقام × المقام · نبسّط بعد الضرب · «من» تعني الضرب (ثلث النصف = سدس)
Exemples du cahier : 1/2 × 3/4 = 3/8 · قرأ المختار ثلثي كتاب فيه 60 صفحة = 40."""
import asyncio, json, subprocess
from pathlib import Path

import edge_tts
import imageio_ffmpeg

VOICE = "ar-SA-HamedNeural"
RATE = "-3%"

SEGMENTS = [
    ("intro1", "أهلًا بكم يا أبطال الرياضيات! درسُ اليوم من الوحدة الحادية عشرة: ضرب الكسور."),
    ("intro2", "في هذا الدرس سنتعلم كيف نضرب كسرين، وكيف نبسّط الكسر الناتج، "
               "وسنحلّ مسائل من حياتنا اليومية."),
    # ── القاعدة ──
    ("rule1", "قاعدة ضرب الكسور سهلة جدًا: أضرب البسط في البسط، وأضرب المقام في المقام."),
    ("rule2", "وبعد الضرب، لا أنسى أن أبسّط الكسر الناتج إن أمكن."),
    # ── المثال : 1/2 × 3/4 = 3/8 ──
    ("ex1", "لنأخذ مثالًا من كراسنا: النصف في ثلاثة أرباع."),
    ("ex2", "أضرب البسطين أولًا: واحد في ثلاثة يساوي ثلاثة. أكتب ثلاثة في بسط الناتج."),
    ("ex3", "ثم أضرب المقامين: اثنان في أربعة يساوي ثمانية. أكتب ثمانية في مقام الناتج."),
    ("ex4", "وهكذا حصلنا على الناتج: ثلاثة أثمان."),
    # ── أتحقق بالرسم : ثلث النصف ──
    ("ver1", "وإليكم ملاحظة مهمة: كلمة مِن تعني الضرب! فثلث النصف يعني: الثلث في النصف."),
    ("ver2", "انظروا إلى الشريط: لوّنا النصف، ثم قسمناه إلى ثلاث حصص وأخذنا حصة واحدة، "
             "فحصلنا على سدس الكل. إذن الثلث في النصف يساوي السدس."),
    # ── مسألة من الكراس ──
    ("app1", "لنحلّ الآن مسألة من الكراس: قرأ المختار ثلثي كتاب فيه ستون صفحة. كم صفحة قرأ؟"),
    ("app2", "أقسم الستين على ثلاثة، فيكون الثلث الواحد عشرين صفحة، "
             "والثلثان أربعين صفحة. قرأ المختار أربعين صفحة!"),
    # ── انتبه ──
    ("att1", "انتبه جيدًا! هذه القاعدة خاصة بالضرب فقط: في جمع الكسور لا نجمع المقامات أبدًا."),
    # ── السر ──
    ("astuce", "وقبل أن نفترق، إليك سرًّا ذهبيًا: بعد كل عملية ضرب، ابحث هل يمكن تبسيط الناتج. "
               "اثنان على ثلاثة في ثلاثة على أربعة يساوي ستة على اثني عشر، وبعد التبسيط: النصف!"),
    ("outro", "والآن افتح كراسك وحلّ تمارين الوحدة الحادية عشرة. إلى اللقاء يا أبطال!"),
]

OUT = Path(__file__).parent / "audio_u11"


async def main():
    OUT.mkdir(exist_ok=True)
    ff = imageio_ffmpeg.get_ffmpeg_exe()
    durations = {}
    for name, text in SEGMENTS:
        mp3 = OUT / f"{name}.mp3"
        await edge_tts.Communicate(text, VOICE, rate=RATE).save(str(mp3))
        r = subprocess.run([ff, "-i", str(mp3), "-f", "null", "-"],
                           capture_output=True, text=True)
        for line in r.stderr.splitlines():
            if "time=" in line:
                t = line.split("time=")[1].split(" ")[0]
                h, m, s = t.split(":")
                durations[name] = round(int(h) * 3600 + int(m) * 60 + float(s), 2)
        print(f"{name}: {durations.get(name, '?')} s")
    (OUT / "durations.json").write_text(json.dumps(durations, indent=2))
    print("total:", round(sum(durations.values()), 1), "s")


if __name__ == "__main__":
    asyncio.run(main())
