# -*- coding: utf-8 -*-
"""Narration U16 — مضاعفات الأعداد وقواسمها. Fidèle au cahier (unites_4.py u16) :
المضاعفات بالضرب في 0،1،2،3… · القواسم = قسمة تامة (210÷30=7) ·
قواعد قابلية القسمة على 2/3/5/9/10 (والـ6 = 2 و3 معًا) ·
مثال 414 : 4+1+4=9 ← يقبل ÷3 و÷9 · مسألة قوارير الحليب 270÷90=3."""
import asyncio, json, subprocess
from pathlib import Path

import edge_tts
import imageio_ffmpeg

VOICE = "ar-SA-HamedNeural"
RATE = "-3%"

SEGMENTS = [
    ("intro1", "أهلًا بكم يا أبطال الرياضيات! درسُ اليوم من الوحدة السادسة عشرة: "
               "مضاعفات الأعداد وقواسمها."),
    ("intro2", "في هذا الدرس سنميّز مضاعفات العدد وقواسمه، "
               "وسنتعلم قواعد ذهبية تخبرنا هل يقبل العدد القسمة دون أن نحسبها."),
    # ── المضاعفات ──
    ("mul1", "ما هي مضاعفات العدد؟ نحصل عليها بضربه في صفر، وواحد، واثنين، وثلاثة، وهكذا."),
    ("mul2", "مضاعفات الخمسة مثلًا: صفر، خمسة، عشرة، خمسة عشر، عشرون. "
             "على المستقيم العددي أقفز خمسة في كل مرة!"),
    # ── القواسم ──
    ("div1", "أما قواسم العدد فهي الأعداد التي تقسمه قسمة تامة دون باق."),
    ("div2", "انظروا: مئتان وعشرة على ثلاثين تساوي سبعة تمامًا. "
             "إذن ثلاثون قاسم لمئتين وعشرة، ومئتان وعشرة مضاعف لثلاثين."),
    # ── قواعد قابلية القسمة ──
    ("reg1", "والآن القواعد الذهبية! يقبل العدد القسمة على اثنين إذا كان زوجيًا: "
             "ينتهي بصفر أو اثنين أو أربعة أو ستة أو ثمانية."),
    ("reg2", "ويقبل القسمة على خمسة إذا انتهى بصفر أو خمسة، "
             "ويقبل القسمة على عشرة إذا انتهى بصفر."),
    ("reg3", "ويقبل القسمة على ثلاثة إذا كان مجموع أرقامه يقبل القسمة على ثلاثة، "
             "وعلى تسعة إذا كان مجموع أرقامه يقبل القسمة على تسعة."),
    ("reg4", "وأما الستة فتجمع بين قاعدتين: يقبل العدد القسمة على ستة "
             "إذا قبل القسمة على اثنين وثلاثة معًا."),
    # ── مثال محوري : 414 ──
    ("ex1", "لنطبّق على العدد أربعمئة وأربعة عشر: أجمع أرقامه: "
            "أربعة زائد واحد زائد أربعة: تسعة."),
    ("ex2", "تسعة تقبل القسمة على ثلاثة وعلى تسعة: "
            "إذن أربعمئة وأربعة عشر يقبل القسمة على ثلاثة وتسعة معًا، دون أي عملية قسمة!"),
    # ── مسألة من الحياة ──
    ("app1", "مسألة من حياتنا: عندنا مئتان وسبعون سنتيلترًا من الحليب، "
             "وقارورات سعة الواحدة تسعون سنتيلترًا. كم قارورة نملأ؟"),
    ("app2", "مئتان وسبعون على تسعين تساوي ثلاثة تمامًا: نملأ ثلاث قارورات، "
             "لأن مئتين وسبعين مضاعف لتسعين."),
    # ── انتبه ──
    ("att1", "انتبه جيدًا! لا تخلط بين المضاعف والقاسم: "
             "المضاعف أكبر من العدد أو يساويه، والقاسم أصغر منه أو يساويه."),
    # ── السر ──
    ("astuce", "وقبل أن نفترق، إليك سرًّا ذهبيًا: لفحص القسمة على ثلاثة أو تسعة "
               "لا تحتاج إلى القسمة أبدًا: اجمع الأرقام فقط، والمجموع يخبرك بكل شيء!"),
    ("outro", "والآن افتح كراسك وحلّ تمارين الوحدة السادسة عشرة. إلى اللقاء يا أبطال!"),
]

OUT = Path(__file__).parent / "audio_u16"


async def main():
    OUT.mkdir(exist_ok=True)
    ff = imageio_ffmpeg.get_ffmpeg_exe()
    durations = {}
    for name, text in SEGMENTS:
        mp3 = OUT / f"{name}.mp3"
        await edge_tts.Communicate(text, VOICE, rate=RATE).save(str(mp3))
        r = subprocess.run([ff, "-i", str(mp3), "-f", "null", "-"],
                           capture_output=True, text=True)
        for line in r.stderr.splitlines():
            if "time=" in line:
                t = line.split("time=")[1].split(" ")[0]
                h, m, s = t.split(":")
                durations[name] = round(int(h) * 3600 + int(m) * 60 + float(s), 2)
        print(f"{name}: {durations.get(name, '?')} s")
    (OUT / "durations.json").write_text(json.dumps(durations, indent=2))
    print("total:", round(sum(durations.values()), 1), "s")


if __name__ == "__main__":
    asyncio.run(main())
