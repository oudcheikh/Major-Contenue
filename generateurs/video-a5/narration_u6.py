# -*- coding: utf-8 -*-
"""Narration U6 — قياس الأطوال. Fidèle au cahier :
mm سُمك بطاقة · cm عرض إصبع · m مسطرة التلميذ ×3 · km بين مدينتين ·
1m=100cm · 1cm=10mm · 1km=1000m · جدول التحويل (رقم في عمود الوحدة ثم أصفار) ·
مثال 5m=500cm · شريط 2m و35cm = 235cm · سلم الوحدات ×10/÷10."""
import asyncio, json, subprocess
from pathlib import Path

import edge_tts
import imageio_ffmpeg

VOICE = "ar-SA-HamedNeural"
RATE = "-3%"

SEGMENTS = [
    ("intro1", "أهلًا بكم يا أبطال الرياضيات! درسُ اليوم من الوحدة السادسة: قياس الأطوال."),
    ("intro2", "في هذا الدرس سنميّز وحدات الطول ونختار المناسبة منها، "
               "وسنحوّل الأطوال من وحدة إلى أخرى بجدول التحويل، "
               "وسنحلّ مسائل بجمع الأطوال وطرحها."),
    # ── الوحدات الأربع ──
    ("unit1", "قياس الطول هو معرفة عدد وحدات القياس في المسافة. "
              "وهذه أشهر الوحدات: المليمتر، والسنتيمتر، والمتر، والكيلومتر."),
    ("unit2", "المليمتر للأطوال الصغيرة جدًا مثل سُمك البطاقة، "
              "والسنتيمتر يساوي عرض إصبعك تقريبًا."),
    ("unit3", "والمتر يساوي طول مسطرة التلميذ ثلاث مرات، "
              "والكيلومتر للمسافات الكبيرة بين المدن."),
    ("rel1", "احفظوا معي: المتر مائة سنتيمتر، والسنتيمتر عشرة مليمترات، "
             "والكيلومتر ألف متر."),
    # ── أقيس بالمسطرة ──
    ("mes1", "لنقس قلمًا بالمسطرة: أضع طرف القلم عند الصفر، "
             "وأقرأ عند الطرف الآخر: ثمانية. إذن طول القلم ثمانية سنتيمترات."),
    # ── جدول التحويل ──
    ("conv1", "وللتحويل بين الوحدات نستعمل جدول التحويل: "
              "لكل وحدة عمود، من الكيلومتر إلى المليمتر."),
    ("conv2", "لنحوّل خمسة أمتار إلى سنتيمترات: أضع الرقم خمسة في عمود المتر."),
    ("conv3", "ثم أكمل بصفر في كل عمود حتى أصل إلى الوحدة المطلوبة: "
              "صفر في الديسيمتر، وصفر في السنتيمتر."),
    ("conv4", "وأقرأ العدد كاملًا: خمسمائة. إذن خمسة أمتار تساوي خمسمائة سنتيمتر!"),
    ("ex1", "مثال آخر: شريط طوله متران وخمسة وثلاثون سنتيمترًا. "
            "المتران يساويان مائتي سنتيمتر، ومائتان زائد خمسة وثلاثين "
            "يساوي مائتين وخمسة وثلاثين سنتيمترًا."),
    # ── انتبه ──
    ("att1", "انتبه جيدًا! المتر مائة سنتيمتر وليس عشرة! "
             "ولا تخلط بين السنتيمتر والمليمتر: عرض إصبعك سنتيمتر واحد أي عشرة مليمترات."),
    # ── السر ──
    ("astuce", "وقبل أن نفترق، إليك سرًّا صغيرًا: في سلم الوحدات، "
               "كل درجة نزولًا نضرب في عشرة، وكل درجة صعودًا نقسم على عشرة."),
    ("outro", "والآن افتح كراسك وحلّ تمارين الوحدة السادسة. إلى اللقاء يا أبطال!"),
]

OUT = Path(__file__).parent / "audio_u6"


async def main():
    OUT.mkdir(exist_ok=True)
    ff = imageio_ffmpeg.get_ffmpeg_exe()
    durations = {}
    for name, text in SEGMENTS:
        mp3 = OUT / f"{name}.mp3"
        await edge_tts.Communicate(text, VOICE, rate=RATE).save(str(mp3))
        r = subprocess.run([ff, "-i", str(mp3), "-f", "null", "-"],
                           capture_output=True, text=True)
        for line in r.stderr.splitlines():
            if "time=" in line:
                t = line.split("time=")[1].split(" ")[0]
                h, m, s = t.split(":")
                durations[name] = round(int(h) * 3600 + int(m) * 60 + float(s), 2)
        print(f"{name}: {durations.get(name, '?')} s")
    (OUT / "durations.json").write_text(json.dumps(durations, indent=2))
    print("total:", round(sum(durations.values()), 1), "s")


if __name__ == "__main__":
    asyncio.run(main())
