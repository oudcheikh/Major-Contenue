# -*- coding: utf-8 -*-
"""Narration U1 — الأعداد الكبيرة. Voix فصحى (ar-SA-HamedNeural).
Découpage fin : 1 phrase = 1 chunk audio = 1 animation synchronisée.
Vocabulaire strictement aligné sur la page U1 du cahier :
خانة · خانات الأعداد · الصيغة القياسية/التفكيكية/اللفظية · ثلاثةً ثلاثةً انطلاقًا من اليمين."""
import asyncio, json, subprocess
from pathlib import Path

import edge_tts
import imageio_ffmpeg

VOICE = "ar-SA-HamedNeural"    # فصحى — l'utilisateur a rejeté la voix égyptienne
RATE = "-3%"                   # -6% sonnait traînant ; -3% = plus naturel

SEGMENTS = [
    # ── intro ──
    ("intro1", "أهلًا بكم يا أبطال الرياضيات! درسُ اليوم من الوحدة الأولى: الأعدادُ الكبيرة."),
    ("intro2", "في هذا الدرس سنتعلم كيف نقرأ الأعداد الكبيرة وكيف نكتبها، وسنتعرف على خانات الأعداد."),
    # ── القاعدة ──
    ("regle1", "الأعداد الكبيرة تمتد من الألف إلى المليون وأكثر."),
    ("regle2", "ولكي نقرأ عددًا كبيرًا بسهولة، نجمع أرقامه ثلاثةً ثلاثةً انطلاقًا من اليمين."),
    ("regle3", "ونسمي هذه المجموعات: الوحدات، ثم الآلاف، ثم الملايين، ثم المليارات."),
    # ── خانات الأعداد ──
    ("tab1", "وهذا هو جدول خانات الأعداد. لكل رقم خانته: "
             "خانة الوحدات، وخانة العشرات، وخانة المئات، ثم الآلاف، وعشرات الآلاف، ومئات الآلاف."),
    ("tab2", "لنضع العدد مئتين وخمسة وأربعين ألفًا في الجدول، رقمًا رقمًا انطلاقًا من اليمين: "
             "صفر في خانة الوحدات، وصفر في خانة العشرات، وصفر في خانة المئات، "
             "ثم خمسة في خانة الآلاف، وأربعة في عشرات الآلاف، واثنان في مئات الآلاف."),
    ("tab3", "والآن نقرأ العدد بكل سهولة: مئتان وخمسة وأربعون ألفًا."),
    # ── الصيغ الثلاث ──
    ("sigh1", "وللعدد ثلاث صيغ كما في كراسك تمامًا. الصيغة القياسية: نكتب العدد بالأرقام."),
    ("sigh2", "الصيغة التفكيكية: نفكك العدد بالنشر والجمع: مئتان وخمسة وأربعون في الألف."),
    ("sigh3", "والصيغة اللفظية: نكتب العدد بالحروف."),
    # ── الطريقة (appliquée pas à pas sur 6 084 512) ──
    ("meth0", "والآن إليكم الطريقة لقراءة أي عدد كبير. لنطبقها معًا على هذا العدد."),
    ("meth1", "الخطوة الأولى: أجمع الأرقام ثلاثةً ثلاثةً انطلاقًا من اليمين. هكذا!"),
    ("meth2a", "الخطوة الثانية: أقرأ كل مجموعة وأتبعها باسمها."),
    ("meth2b", "هذه مجموعة الملايين: أقول ستة ملايين."),
    ("meth2c", "وهذه مجموعة الآلاف: أقول وأربعة وثمانون ألفًا."),
    ("meth3", "الخطوة الثالثة: المجموعة الأخيرة، مجموعة الوحدات، أقرؤها دون اسم: وخمسمائة واثنا عشر."),
    ("meth4", "رائع! لقد قرأنا العدد كاملًا: ستة ملايين وأربعة وثمانون ألفًا وخمسمائة واثنا عشر."),
    # ── انتبه ──
    ("att1", "انتبه جيدًا! لا تنسَ الأصفار في وسط العدد."),
    ("att2", "ثلاثة ملايين وخمسة: نكتب ثلاثة، ثم خمسة أصفار، ثم خمسة. وليس ثلاثة وخمسة فقط!"),
    ("att3", "تذكر دائمًا: الصفر يحفظ مكان الخانة."),
    # ── السر + الختام ──
    ("astuce", "وقبل أن نفترق، إليك سرًّا صغيرًا: قبل قراءة أي عدد كبير، "
               "ضع خطًا صغيرًا بعد كل ثلاثة أرقام انطلاقًا من اليمين، وهكذا لن تضيع بين الخانات أبدًا."),
    ("outro", "والآن افتح كراسك وحلّ تمارين الوحدة الأولى. إلى اللقاء يا أبطال!"),
]

OUT = Path(__file__).parent / "audio_u1"


async def main():
    OUT.mkdir(exist_ok=True)
    ff = imageio_ffmpeg.get_ffmpeg_exe()
    durations = {}
    for name, text in SEGMENTS:
        mp3 = OUT / f"{name}.mp3"
        await edge_tts.Communicate(text, VOICE, rate=RATE).save(str(mp3))
        r = subprocess.run([ff, "-i", str(mp3), "-f", "null", "-"],
                           capture_output=True, text=True)
        for line in r.stderr.splitlines():
            if "time=" in line:
                t = line.split("time=")[1].split(" ")[0]
                h, m, s = t.split(":")
                durations[name] = round(int(h) * 3600 + int(m) * 60 + float(s), 2)
        print(f"{name}: {durations.get(name, '?')} s")
    (OUT / "durations.json").write_text(json.dumps(durations, indent=2))
    print("total:", round(sum(durations.values()), 1), "s")


if __name__ == "__main__":
    asyncio.run(main())
