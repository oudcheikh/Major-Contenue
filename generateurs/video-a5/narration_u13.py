# -*- coding: utf-8 -*-
"""Narration U13 — الشراء والبيع. Fidèle au cahier (unites_3.py u13) :
ثمن الشراء/ثمن البيع · الربح = البيع − الشراء · الخسارة = الشراء − البيع ·
الكلفة = الشراء + المصاريف. Exemples du cahier (بالأوقية) :
كتاب 180 → 250 (ربح 70) · إبريق أتاي 350 → 300 (خسارة 50) · سلعة 500 + نقل 50 → بيع 620 (ربح 70)."""
import asyncio, json, subprocess
from pathlib import Path

import edge_tts
import imageio_ffmpeg

VOICE = "ar-SA-HamedNeural"
RATE = "-3%"

SEGMENTS = [
    ("intro1", "أهلًا بكم يا أبطال الرياضيات! درسُ اليوم من الوحدة الثالثة عشرة: الشراء والبيع."),
    ("intro2", "في هذا الدرس سنفرّق بين ثمن الشراء وثمن البيع، "
               "وسنحسب الربح والخسارة والكلفة بالأوقية."),
    # ── في السوق : التعريفات ──
    ("def1", "في السوق، يدفع التاجر نقودًا ليحصل على السلعة: هذا هو ثمن الشراء."),
    ("def2", "ثم يعرض السلعة على الزبائن ويبيعها: والثمن الذي يبيع به هو ثمن البيع."),
    ("def3", "فإذا باع بثمن أعلى من ثمن الشراء فقد ربح، وإذا باع بثمن أقل فقد خسر."),
    # ── القاعدة ──
    ("form1", "احفظوا القاعدة الأولى جيدًا: الربح يساوي ثمن البيع ناقص ثمن الشراء."),
    # ── مثال الربح : كتاب 180 → 250 ──
    ("ex1", "لنحسب معًا: اشترى التاجر كتابًا بمئة وثمانين أوقية، وباعه بمئتين وخمسين أوقية."),
    ("ex2", "الربح يساوي مئتين وخمسين ناقص مئة وثمانين: سبعون أوقية. تاجرنا رابح!"),
    # ── مثال الخسارة : إبريق أتاي 350 → 300 ──
    ("loss1", "وماذا لو باع بثمن أقل؟ اشترى بائع إبريق أتاي بثلاثمئة وخمسين أوقية، "
              "وباعه بثلاثمئة أوقية فقط."),
    ("loss2", "الخسارة تساوي ثلاثمئة وخمسين ناقص ثلاثمئة: خمسون أوقية. "
              "في الخسارة نحسب: ثمن الشراء ناقص ثمن البيع."),
    # ── الكلفة : 500 + 50 → بيع 620 ──
    ("cost1", "وأحيانًا يدفع التاجر مصاريف إضافية كأجرة النقل: "
              "فتكون الكلفة هي ثمن الشراء زائد المصاريف."),
    ("cost2", "مثال: اشترى تاجر سلعة بخمسمئة أوقية، ودفع خمسين أوقية للنقل: "
              "فالكلفة خمسمئة وخمسون أوقية."),
    ("cost3", "ثم باع السلعة بستمئة وعشرين أوقية: "
              "فالربح يساوي ستمئة وعشرين ناقص خمسمئة وخمسين: سبعون أوقية."),
    # ── انتبه ──
    ("att1", "انتبه جيدًا! لا تنسَ المصاريف: الربح الحقيقي يُحسب من الكلفة، "
             "لا من ثمن الشراء وحده."),
    # ── السر ──
    ("astuce", "وقبل أن نفترق، إليك سرًّا ذهبيًا: قارن دائمًا ثمن البيع بثمن الشراء: "
               "إن كان البيع أكبر فهو ربح، وإن كان البيع أصغر فهي خسارة."),
    ("outro", "والآن افتح كراسك وحلّ تمارين الوحدة الثالثة عشرة. إلى اللقاء يا أبطال!"),
]

OUT = Path(__file__).parent / "audio_u13"


async def main():
    OUT.mkdir(exist_ok=True)
    ff = imageio_ffmpeg.get_ffmpeg_exe()
    durations = {}
    for name, text in SEGMENTS:
        mp3 = OUT / f"{name}.mp3"
        await edge_tts.Communicate(text, VOICE, rate=RATE).save(str(mp3))
        r = subprocess.run([ff, "-i", str(mp3), "-f", "null", "-"],
                           capture_output=True, text=True)
        for line in r.stderr.splitlines():
            if "time=" in line:
                t = line.split("time=")[1].split(" ")[0]
                h, m, s = t.split(":")
                durations[name] = round(int(h) * 3600 + int(m) * 60 + float(s), 2)
        print(f"{name}: {durations.get(name, '?')} s")
    (OUT / "durations.json").write_text(json.dumps(durations, indent=2))
    print("total:", round(sum(durations.values()), 1), "s")


if __name__ == "__main__":
    asyncio.run(main())
