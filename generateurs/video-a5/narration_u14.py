# -*- coding: utf-8 -*-
"""Narration U14 — الأعداد العشرية. Fidèle au cahier (unites_3.py u14) :
الفاصلة · الجزء الصحيح/الجزء العشري · خانة الأعشار وخانة الأجزاء من المئة ·
المقارنة (أساوي عدد الأرقام بإضافة أصفار: 6,4 و6,09) · الجمع عموديًا (1,5+2,3=3,8) ·
انتبه: نسيان الفاصلة في الناتج · السر: 3,5 = 3,50."""
import asyncio, json, subprocess
from pathlib import Path

import edge_tts
import imageio_ffmpeg

VOICE = "ar-SA-HamedNeural"
RATE = "-3%"

SEGMENTS = [
    ("intro1", "أهلًا بكم يا أبطال الرياضيات! درسُ اليوم من الوحدة الرابعة عشرة: الأعداد العشرية."),
    ("intro2", "في هذا الدرس سنقرأ الأعداد العشرية ونكتبها بالفاصلة، "
               "وسنقارنها ونرتّبها، ثم نجمعها ونطرحها."),
    # ── تعريف : الفاصلة والجزءان ──
    ("def1", "العدد العشري هو عدد يُكتب بفاصلة: الجزء قبل الفاصلة هو الجزء الصحيح، "
             "والجزء بعد الفاصلة هو الجزء العشري."),
    ("def2", "انظروا إلى هذا العدد: نقرأ الجزء الصحيح أولًا، ثم الفاصلة، ثم الجزء العشري: "
             "ثلاثة فاصلة خمسة وسبعون."),
    # ── جدول الخانات ──
    ("tab1", "ولكل رقم خانتُه في الجدول: الوحدات، ثم الفاصلة، ثم الأعشار، ثم الأجزاء من المئة."),
    ("tab2", "الثلاثة تسكن في خانة الوحدات، والسبعة في خانة الأعشار، "
             "والخمسة في خانة الأجزاء من المئة."),
    # ── المقارنة : 6,4 و 6,09 ──
    ("comp1", "والآن المقارنة! لنقارن بين ستة فاصلة أربعة وستة فاصلة صفر تسعة."),
    ("comp2", "أولًا أساوي عدد الأرقام بعد الفاصلة بإضافة صفر: "
              "ستة فاصلة أربعة تصبح ستة فاصلة أربعين."),
    ("comp3", "ثم أقارن خانة بخانة: الجزء الصحيح ستة يساوي ستة، وفي خانة الأعشار أربعة أكبر من صفر: "
              "إذن ستة فاصلة أربعة أكبر من ستة فاصلة صفر تسعة."),
    # ── الجمع عموديًا : 1,5 + 2,3 ──
    ("op1", "ولجمع الأعداد العشرية أو طرحها، أضعها عموديًا وأتذكر القاعدة الذهبية: "
            "الفاصلة تحت الفاصلة!"),
    ("op2", "لنجمع واحدًا فاصلة خمسة مع اثنين فاصلة ثلاثة: "
            "أكتب العددين بعضهما تحت بعض، والفاصلة تحت الفاصلة تمامًا."),
    ("op3", "في خانة الأعشار: خمسة زائد ثلاثة: ثمانية. وفي خانة الوحدات: واحد زائد اثنين: ثلاثة. "
            "ثم أُنزل الفاصلة في الناتج: ثلاثة فاصلة ثمانية."),
    # ── انتبه ──
    ("att1", "انتبه جيدًا! نسيان الفاصلة في الناتج أشهر خطأ: "
             "ضعها دائمًا تحت فاصلتَي العددين."),
    # ── السر ──
    ("astuce", "وقبل أن نفترق، إليك سرًّا ذهبيًا: إذا أضفتُ صفرًا في آخر الجزء العشري "
               "فإن العدد لا يتغير: ثلاثة فاصلة خمسة هي نفسها ثلاثة فاصلة خمسين!"),
    ("outro", "والآن افتح كراسك وحلّ تمارين الوحدة الرابعة عشرة. إلى اللقاء يا أبطال!"),
]

OUT = Path(__file__).parent / "audio_u14"


async def main():
    OUT.mkdir(exist_ok=True)
    ff = imageio_ffmpeg.get_ffmpeg_exe()
    durations = {}
    for name, text in SEGMENTS:
        mp3 = OUT / f"{name}.mp3"
        await edge_tts.Communicate(text, VOICE, rate=RATE).save(str(mp3))
        r = subprocess.run([ff, "-i", str(mp3), "-f", "null", "-"],
                           capture_output=True, text=True)
        for line in r.stderr.splitlines():
            if "time=" in line:
                t = line.split("time=")[1].split(" ")[0]
                h, m, s = t.split(":")
                durations[name] = round(int(h) * 3600 + int(m) * 60 + float(s), 2)
        print(f"{name}: {durations.get(name, '?')} s")
    (OUT / "durations.json").write_text(json.dumps(durations, indent=2))
    print("total:", round(sum(durations.values()), 1), "s")


if __name__ == "__main__":
    asyncio.run(main())
