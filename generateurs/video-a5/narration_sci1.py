# -*- coding: utf-8 -*-
"""Narration Sciences 1 — التوازن الغذائي. Fidèle au cahier (sciences_1.py, s1_*) :
6 مجموعات غذائية · الأدوار الثلاثة: الطاقة والنمو والحماية · 3 وجبات + الماء ·
الصحن المتوازن · مثال محلول: تفاحة + كوب حليب = 230 kcal · مائدتنا الموريتانية."""
import asyncio, json, subprocess
from pathlib import Path

import edge_tts
import imageio_ffmpeg

VOICE = "ar-SA-HamedNeural"
RATE = "-3%"

SEGMENTS = [
    ("intro1", "أهلًا بكم يا أبطال العلوم! درسُ اليوم من مادة العلوم الطبيعية: "
               "التوازن الغذائي."),
    ("intro2", "في هذا الدرس سنتعرف على المجموعات الغذائية، ودور كل مجموعة، "
               "وكيف نركّب وجبة متوازنة من مائدتنا."),
    # ── ما هو التوازن الغذائي ──
    ("def1", "التوازن الغذائي هو أن نتناول أطعمة متنوعة بكميات مناسبة "
             "للحفاظ على صحة أجسامنا."),
    # ── المجموعات الست ──
    ("grp1", "تنقسم الأطعمة إلى ست مجموعات: الفواكه والخضروات، والنشويات، "
             "ومنتجات الألبان، واللحوم والأسماك والبيض، والدهون، والمنتجات السكرية."),
    # ── الأدوار الثلاثة ──
    ("role1", "ولكل مجموعة دورها: فمنها ما يعطينا الطاقة، "
              "ومنها ما يساعد على النمو، ومنها ما يحمي الجسم."),
    # ── الصحن المتوازن ──
    ("plate1", "انظر إلى صحني المتوازن: نصفه خضروات وفواكه للحماية، "
               "وربعه نشويات للطاقة، وربعه بروتينات للنمو، وقليل جدًا من السكر."),
    # ── ثلاث وجبات ──
    ("meal1", "ومن المهم أن نتناول ثلاث وجبات في اليوم: الإفطار والغداء والعشاء، "
              "مع شرب الماء الكافي."),
    # ── مثال محلول من الكراس ──
    ("ex1", "لنطبّق معًا مثالًا من كراسك: تفاحة تعطي ثمانين سعرة، "
            "وكوب حليب يعطي مائة وخمسين سعرة."),
    ("ex2", "فإذا جمعناهما: ثمانون زائد مائة وخمسين يساوي مائتين وثلاثين سعرة حرارية. "
            "وجبة خفيفة متوازنة!"),
    # ── انتبه ──
    ("att1", "انتبه جيدًا! الخضروات وحدها لا تكفي الجسم، "
             "فالجسم يحتاج إلى كل المجموعات الغذائية معًا."),
    # ── السر: مائدتنا ──
    ("astuce", "وإليك سرًّا من مائدتنا الموريتانية: طبق الأرز بالسمك يجمع النشويات والبروتينات، "
               "أضِف إليه الخضروات وكوب حليب، فتكتمل وجبتك المتوازنة!"),
    ("outro", "والآن افتح كراسك وحلّ تمارين درس التوازن الغذائي. إلى اللقاء يا أبطال!"),
]

OUT = Path(__file__).parent / "audio_sci1"


async def main():
    OUT.mkdir(exist_ok=True)
    ff = imageio_ffmpeg.get_ffmpeg_exe()
    durations = {}
    for name, text in SEGMENTS:
        mp3 = OUT / f"{name}.mp3"
        await edge_tts.Communicate(text, VOICE, rate=RATE).save(str(mp3))
        r = subprocess.run([ff, "-i", str(mp3), "-f", "null", "-"],
                           capture_output=True, text=True)
        for line in r.stderr.splitlines():
            if "time=" in line:
                t = line.split("time=")[1].split(" ")[0]
                h, m, s = t.split(":")
                durations[name] = round(int(h) * 3600 + int(m) * 60 + float(s), 2)
        print(f"{name}: {durations.get(name, '?')} s")
    (OUT / "durations.json").write_text(json.dumps(durations, indent=2))
    print("total:", round(sum(durations.values()), 1), "s")


if __name__ == "__main__":
    asyncio.run(main())
