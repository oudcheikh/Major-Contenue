# -*- coding: utf-8 -*-
"""Narration U27 — المثلثات. Fidèle au cahier (u27_p1..p5) :
الأنواع (كيفي، قائم، متساوي الساقين، متساوي الأضلاع) · الإنشاء بالمسطرة والمدور ·
الارتفاع = العمود النازل من الرأس على القاعدة · المساحة = القاعدة × الارتفاع ÷ 2.
Exemples du cahier : إنشاء 3-4-5 (القاعدة 5) · المساحة 6 × 4 ÷ 2 = 12 cm²."""
import asyncio, json, subprocess
from pathlib import Path

import edge_tts
import imageio_ffmpeg

VOICE = "ar-SA-HamedNeural"
RATE = "-3%"

SEGMENTS = [
    ("intro1", "أهلًا بكم يا أبطال الرياضيات! درسُ اليوم من الوحدة السابعة والعشرين: المثلثات."),
    ("intro2", "في هذا الدرس سنتعرّف أنواع المثلثات، وننشئها بالمسطرة والمدور، "
               "ونحسب مساحتها بالقاعدة والارتفاع."),
    # ── الأنواع ──
    ("typ1", "للمثلث ثلاثة أضلاع وثلاث زوايا وثلاثة رؤوس."),
    ("typ2", "هذا هو المثلث الكيفي: لا خاصية خاصة له، فأضلاعه مختلفة الأطوال."),
    ("typ3", "وهذا قائم الزاوية: فيه زاوية قائمة واحدة، نعلّمها بمربع صغير."),
    ("typ4", "وهذا متساوي الساقين: فيه ضلعان متساويان، نعلّمهما بشرطتين متشابهتين."),
    ("typ5", "وهذا متساوي الأضلاع: أضلاعه الثلاثة متساوية، وزواياه الثلاث متساوية أيضًا."),
    # ── الإنشاء بالمسطرة والمدور : 3-4-5 ──
    ("cons1", "كيف أنشئ مثلثًا أعرف أطوال أضلاعه؟ أبدأ دائمًا بأطول ضلع، "
              "فأرسم بالمسطرة القاعدة: خمسة سنتيمترات."),
    ("cons2", "ثم أرسم بالمدور قوسًا مركزه النقطة باء ونصف قطره ثلاثة سنتيمترات، "
              "وقوسًا مركزه النقطة جيم ونصف قطره أربعة سنتيمترات، "
              "وتقاطع القوسين هو الرأس ألف."),
    # ── الارتفاع ──
    ("haut1", "والآن الارتفاع: هو العمود النازل من الرأس على الضلع المقابل، "
              "ونسمّي هذا الضلع القاعدة."),
    # ── المساحة ──
    ("aire1", "قاعدة ذهبية: مساحة المثلث تساوي القاعدة في الارتفاع على اثنين."),
    ("aire2", "لنطبّق معًا: مثلث قاعدته ستة سنتيمترات وارتفاعه أربعة سنتيمترات: "
              "ستة في أربعة يساوي أربعة وعشرين، "
              "وأربعة وعشرون على اثنين يساوي اثني عشر سنتيمترًا مربعًا."),
    # ── انتبه ──
    ("att1", "انتبه جيدًا! في مساحة المثلث لا تنسَ القسمة على اثنين: "
             "اضرب القاعدة في الارتفاع ثم اقسم على اثنين دائمًا."),
    # ── السر ──
    ("astuce", "وقبل أن نفترق، إليك سرًّا ذهبيًا: قبل الإنشاء ارسم شكلًا تقريبيًا بيدك "
               "واكتب عليه الأطوال، ثم ابدأ دائمًا بأطول ضلع."),
    ("outro", "والآن افتح كراسك وحلّ تمارين الوحدة السابعة والعشرين. إلى اللقاء يا أبطال!"),
]

OUT = Path(__file__).parent / "audio_u27"


async def main():
    OUT.mkdir(exist_ok=True)
    ff = imageio_ffmpeg.get_ffmpeg_exe()
    durations = {}
    for name, text in SEGMENTS:
        mp3 = OUT / f"{name}.mp3"
        await edge_tts.Communicate(text, VOICE, rate=RATE).save(str(mp3))
        r = subprocess.run([ff, "-i", str(mp3), "-f", "null", "-"],
                           capture_output=True, text=True)
        for line in r.stderr.splitlines():
            if "time=" in line:
                t = line.split("time=")[1].split(" ")[0]
                h, m, s = t.split(":")
                durations[name] = round(int(h) * 3600 + int(m) * 60 + float(s), 2)
        print(f"{name}: {durations.get(name, '?')} s")
    (OUT / "durations.json").write_text(json.dumps(durations, indent=2))
    print("total:", round(sum(durations.values()), 1), "s")


if __name__ == "__main__":
    asyncio.run(main())
