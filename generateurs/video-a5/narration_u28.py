# -*- coding: utf-8 -*-
"""Narration U28 — الأشكال الرباعية. Fidèle au cahier (u28_p1..p5) :
المربع · المستطيل · المعين · متوازي الأضلاع · شبه المنحرف + خصائصها ·
محيط المربع = الضلع × 4 · محيط المستطيل = (الطول + العرض) × 2.
Exemple du cahier : مربع ضلعه 5 cm ← المحيط 20 cm والمساحة 25 cm²."""
import asyncio, json, subprocess
from pathlib import Path

import edge_tts
import imageio_ffmpeg

VOICE = "ar-SA-HamedNeural"
RATE = "-3%"

SEGMENTS = [
    ("intro1", "أهلًا بكم يا أبطال الرياضيات! درسُ اليوم من الوحدة الثامنة والعشرين: "
               "الأشكال الرباعية."),
    ("intro2", "في هذا الدرس سنتعرّف خصائص المربع والمستطيل والمعين "
               "ومتوازي الأضلاع وشبه المنحرف، وسنحسب المحيط والمساحة."),
    # ── الأشكال الخمسة ──
    ("quad1", "الشكل الرباعي له أربعة أضلاع وأربع زوايا وأربعة رؤوس."),
    ("quad2", "أولًا المربع: أربعة أضلاع متساوية وأربع زوايا قائمة."),
    ("quad3", "ثانيًا المستطيل: أضلاعه المتقابلة متساوية، وزواياه الأربع قائمة، "
              "وبُعداه الطول والعرض."),
    ("quad4", "ثالثًا المعين: أربعة أضلاع متساوية، وقطراه متعامدان."),
    ("quad5", "رابعًا متوازي الأضلاع: أضلاعه المتقابلة متوازية ومتساوية."),
    ("quad6", "وخامسًا شبه المنحرف: له ضلعان متقابلان متوازيان: "
              "القاعدة الكبيرة والقاعدة الصغيرة."),
    # ── الجدول ──
    ("tab1", "لنرتّب ما تعلمناه في جدول صغير يجمع الأشكال الخمسة وخصائصها."),
    # ── المحيط ──
    ("per1", "والآن المحيط: محيط المربع يساوي الضلع في أربعة، "
             "ومحيط المستطيل يساوي الطول زائد العرض، والمجموع في اثنين."),
    # ── مثال : مربع ضلعه 5 cm ──
    ("ex1", "لنطبّق على مربع ضلعه خمسة سنتيمترات: "
            "المحيط خمسة في أربعة يساوي عشرين سنتيمترًا."),
    ("ex2", "والمساحة: الضلع في الضلع: خمسة في خمسة يساوي خمسة وعشرين سنتيمترًا مربعًا."),
    # ── انتبه ──
    ("att1", "انتبه جيدًا! لا تخلط بين المحيط والمساحة: "
             "محيط المستطيل الطول زائد العرض في اثنين، أما مساحته فالطول في العرض."),
    # ── السر ──
    ("astuce", "وقبل أن نفترق، إليك سرًّا ذهبيًا: المحيط هو طول السياج حول الشكل "
               "ويقاس بالمتر، أما المساحة فهي ما بداخل الشكل وتقاس بالمتر المربع."),
    ("outro", "والآن افتح كراسك وحلّ تمارين الوحدة الثامنة والعشرين. إلى اللقاء يا أبطال!"),
]

OUT = Path(__file__).parent / "audio_u28"


async def main():
    OUT.mkdir(exist_ok=True)
    ff = imageio_ffmpeg.get_ffmpeg_exe()
    durations = {}
    for name, text in SEGMENTS:
        mp3 = OUT / f"{name}.mp3"
        await edge_tts.Communicate(text, VOICE, rate=RATE).save(str(mp3))
        r = subprocess.run([ff, "-i", str(mp3), "-f", "null", "-"],
                           capture_output=True, text=True)
        for line in r.stderr.splitlines():
            if "time=" in line:
                t = line.split("time=")[1].split(" ")[0]
                h, m, s = t.split(":")
                durations[name] = round(int(h) * 3600 + int(m) * 60 + float(s), 2)
        print(f"{name}: {durations.get(name, '?')} s")
    (OUT / "durations.json").write_text(json.dumps(durations, indent=2))
    print("total:", round(sum(durations.values()), 1), "s")


if __name__ == "__main__":
    asyncio.run(main())
