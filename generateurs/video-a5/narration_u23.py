# -*- coding: utf-8 -*-
"""Narration U23 — السلم والخرائط. Fidèle au cahier :
السلم كسر بسطه غالبًا 1 · من التصميم إلى الحقيقة أضرب في المقام · العكس أقسم · توحيد الوحدات.
Exemples du cahier : 1/3 000 000 و5 cm انواكشوط–ابوتلميت = 150 km · جدار 7 m بسلم 1/100 = 7 cm."""
import asyncio, json, subprocess
from pathlib import Path

import edge_tts
import imageio_ffmpeg

VOICE = "ar-SA-HamedNeural"
RATE = "-3%"

SEGMENTS = [
    ("intro1", "أهلًا بكم يا أبطال الرياضيات! درسُ اليوم من الوحدة الثالثة والعشرين: السلم والخرائط."),
    ("intro2", "في هذا الدرس سنفهم معنى سلم الخريطة، وسنتعلم حساب البعد الحقيقي انطلاقًا من التصميم، "
               "والعكس أيضًا."),
    # ── المفهوم ──
    ("def1", "هل تأملتم يومًا خريطة موريتانيا؟ بلادنا الشاسعة تدخل كلها في ورقة صغيرة، "
             "والسرّ في ذلك هو السلم."),
    ("def2", "السلم كسر بسطه غالبًا واحد، يخبرنا كم مرة صغّرنا الأبعاد الحقيقية لنرسمها على الورقة."),
    ("def3", "فالسلم واحد على مائة يعني: كل سنتيمتر واحد على التصميم يمثل مائة سنتيمتر في الحقيقة، "
             "أي مترًا واحدًا."),
    # ── من الخريطة إلى الحقيقة : 5 cm × 3 000 000 = 150 km ──
    ("map1", "لننطلق في رحلة! على خريطة موريتانيا بسلم واحد على ثلاثة ملايين، "
             "المسافة بين انواكشوط وابوتلميت ممثلة بخمسة سنتيمترات فقط."),
    ("map2", "من التصميم إلى الحقيقة أضرب في مقام السلم: خمسة في ثلاثة ملايين "
             "يساوي خمسة عشر مليون سنتيمتر."),
    ("map3", "ثم أحوّل إلى وحدة مناسبة: خمسة عشر مليون سنتيمتر تساوي مائة وخمسين كيلومترًا. "
             "يا لها من رحلة طويلة خرجت من خمسة سنتيمترات!"),
    # ── من الحقيقة إلى التصميم : 7 m ÷ 100 = 7 cm ──
    ("inv1", "والآن العكس: جدار طوله سبعة أمتار، نريد رسمه على تصميم بسلم واحد على مائة."),
    ("inv2", "أوحّد الوحدة أولًا: سبعة أمتار تساوي سبعمائة سنتيمتر، "
             "ثم أقسم على مائة: سبعة سنتيمترات على التصميم."),
    # ── القاعدة ──
    ("regle1", "احفظوا القاعدة الذهبية: من التصميم إلى الحقيقة أضرب في المقام، "
               "ومن الحقيقة إلى التصميم أقسم على المقام."),
    # ── انتبه ──
    ("att1", "انتبه جيدًا! وحّد الوحدتين قبل كل حساب: حوّل الأمتار إلى سنتيمترات أولًا، "
             "ولا تقسم أبدًا قبل التحويل."),
    # ── السر ──
    ("astuce", "وقبل أن نفترق، إليكم سرًّا ذهبيًا: إذا طُلب منك السلم نفسه، فاقسم البعد على التصميم "
               "على البعد الحقيقي بعد توحيد الوحدتين: خمسة سنتيمترات على خمسة عشر مليون سنتيمتر "
               "تعطينا واحدًا على ثلاثة ملايين."),
    ("outro", "والآن افتح كراسك وحلّ تمارين الوحدة الثالثة والعشرين. إلى اللقاء يا أبطال!"),
]

OUT = Path(__file__).parent / "audio_u23"


async def main():
    OUT.mkdir(exist_ok=True)
    ff = imageio_ffmpeg.get_ffmpeg_exe()
    durations = {}
    for name, text in SEGMENTS:
        mp3 = OUT / f"{name}.mp3"
        await edge_tts.Communicate(text, VOICE, rate=RATE).save(str(mp3))
        r = subprocess.run([ff, "-i", str(mp3), "-f", "null", "-"],
                           capture_output=True, text=True)
        for line in r.stderr.splitlines():
            if "time=" in line:
                t = line.split("time=")[1].split(" ")[0]
                h, m, s = t.split(":")
                durations[name] = round(int(h) * 3600 + int(m) * 60 + float(s), 2)
        print(f"{name}: {durations.get(name, '?')} s")
    (OUT / "durations.json").write_text(json.dumps(durations, indent=2))
    print("total:", round(sum(durations.values()), 1), "s")


if __name__ == "__main__":
    asyncio.run(main())
