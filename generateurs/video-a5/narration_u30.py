# -*- coding: utf-8 -*-
"""Narration U30 — الدائرة والقرص. Fidèle au cahier :
نصف القطر (نق) والقطر · القطر = نق × 2 · π ≈ 3,14 · المحيط = القطر × 3,14 ·
مساحة القرص = نق × نق × 3,14 · مثال الكراس : نق 5 cm ← محيط 31,4 ← مساحة 78,5."""
import asyncio, json, subprocess
from pathlib import Path

import edge_tts
import imageio_ffmpeg

VOICE = "ar-SA-HamedNeural"
RATE = "-3%"

SEGMENTS = [
    ("intro1", "أهلًا بكم يا أبطال الرياضيات! درسُ اليوم من الوحدة الثلاثين: الدائرة والقرص."),
    ("intro2", "في هذا الدرس سنتعرف على نصف القطر والقطر، "
               "وسنحسب محيط الدائرة ومساحة القرص بالعدد الشهير: باي."),
    # ── الدائرة : المركز ونق والقطر ──
    ("def1", "هذه دائرة. نرسمها بالمدور: أثبّت إبرته في نقطة تسمى المركز، "
             "وأفتحه بمقدار نصف القطر."),
    ("def2", "نصف القطر قطعة تصل المركز بنقطة من الدائرة، "
             "وجميع أنصاف الأقطار في الدائرة الواحدة متساوية."),
    ("def3", "أما القطر فيمر بالمركز، ويساوي ضعف نصف القطر: القطر يساوي نصف القطر في اثنين."),
    # ── العدد π ──
    ("pi1", "والآن تعرّفوا على نجم درسنا: العدد باي، وهو يساوي تقريبًا: ثلاثة فاصلة أربعة عشر."),
    # ── المحيط ──
    ("per1", "محيط الدائرة هو طول خطها الدائري، ونحسبه هكذا: "
             "المحيط يساوي القطر في ثلاثة فاصلة أربعة عشر."),
    ("per2", "وبما أن القطر يساوي نصف القطر في اثنين، يمكننا أيضًا أن نكتب: "
             "المحيط يساوي اثنين في باي في نصف القطر."),
    # ── مثال الكراس : نق = 5 cm ──
    ("ex1", "لنطبّق معًا على دائرة نصف قطرها خمسة سنتيمترات. "
            "القطر يساوي خمسة في اثنين: عشرة سنتيمترات."),
    ("ex2", "فالمحيط يساوي عشرة في ثلاثة فاصلة أربعة عشر: "
            "واحد وثلاثون فاصلة أربعة من السنتيمترات."),
    # ── المساحة ──
    ("area1", "أما مساحة القرص فهي المساحة التي بداخل الدائرة، ونحسبها هكذا: "
              "نصف القطر في نصف القطر في ثلاثة فاصلة أربعة عشر."),
    ("ex3", "في مثالنا: خمسة في خمسة في ثلاثة فاصلة أربعة عشر: "
            "ثمانية وسبعون فاصلة خمسة من السنتيمترات المربعة."),
    # ── انتبه ──
    ("att1", "انتبه جيدًا! لا تأخذ القطر مكان نصف القطر: "
             "إذا كان القطر عشرة سنتيمترات، فنصف القطر خمسة فقط."),
    # ── السر ──
    ("astuce", "وقبل أن نفترق، إليك سرًّا ذهبيًا: المحيط صديق القطر، "
               "والمساحة صديقة نصف القطر مرتين. "
               "ولا تنسَ: المحيط بوحدة عادية، والمساحة بوحدة مربعة!"),
    ("outro", "والآن افتح كراسك وحلّ تمارين الوحدة الثلاثين. إلى اللقاء يا أبطال!"),
]

OUT = Path(__file__).parent / "audio_u30"


async def main():
    OUT.mkdir(exist_ok=True)
    ff = imageio_ffmpeg.get_ffmpeg_exe()
    durations = {}
    for name, text in SEGMENTS:
        mp3 = OUT / f"{name}.mp3"
        await edge_tts.Communicate(text, VOICE, rate=RATE).save(str(mp3))
        r = subprocess.run([ff, "-i", str(mp3), "-f", "null", "-"],
                           capture_output=True, text=True)
        for line in r.stderr.splitlines():
            if "time=" in line:
                t = line.split("time=")[1].split(" ")[0]
                h, m, s = t.split(":")
                durations[name] = round(int(h) * 3600 + int(m) * 60 + float(s), 2)
        print(f"{name}: {durations.get(name, '?')} s")
    (OUT / "durations.json").write_text(json.dumps(durations, indent=2))
    print("total:", round(sum(durations.values()), 1), "s")


if __name__ == "__main__":
    asyncio.run(main())
