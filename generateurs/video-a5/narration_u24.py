# -*- coding: utf-8 -*-
"""Narration U24 — الفائدة السنوية. Fidèle au cahier :
رأس المال · نسبة التوظيف · الفائدة السنوية = رأس المال × النسبة ÷ 100 ·
فائدة عدة أشهر = الفائدة السنوية × عدد الأشهر ÷ 12 · النسبة = الفائدة × 100 ÷ رأس المال.
Exemples du cahier : 20 000 أوقية بنسبة 5 % = 1 000 · فائدة 6 أشهر = 500 · 600 من 10 000 = 6 %."""
import asyncio, json, subprocess
from pathlib import Path

import edge_tts
import imageio_ffmpeg

VOICE = "ar-SA-HamedNeural"
RATE = "-3%"

SEGMENTS = [
    ("intro1", "أهلًا بكم يا أبطال الرياضيات! درسُ اليوم من الوحدة الرابعة والعشرين: الفائدة السنوية."),
    ("intro2", "في هذا الدرس سنتعرف رأس المال والنسبة والفائدة، "
               "وسنحسب فائدة سنة كاملة ثم فائدة عدة أشهر."),
    # ── المفهوم : ثلاث كلمات ──
    ("def1", "من يضع مالًا في البنك لا يبقى مالُه جامدًا، بل ينمو قليلًا كل سنة."),
    ("def2", "المبلغ الموظف يسمى رأس المال، والزيادة التي يمنحها البنك تسمى الفائدة السنوية، "
             "وتُحسب حسب نسبة التوظيف."),
    ("def3", "فالنسبة خمسة في المائة تعني: كل مائة أوقية من رأس المال "
             "تنتج خمس أوقيات فائدة في السنة."),
    # ── القاعدة ──
    ("form1", "والقاعدة الذهبية: الفائدة السنوية تساوي رأس المال في النسبة مقسومًا على مائة."),
    # ── مثال : 20 000 × 5 ÷ 100 = 1 000 ──
    ("ex1", "مثال من سوق العاصمة: وظّف تاجر عشرين ألف أوقية بنسبة خمسة في المائة."),
    ("ex2", "أطبق القاعدة: عشرون ألفًا في خمسة مقسومة على مائة: الفائدة السنوية ألف أوقية."),
    # ── فائدة عدة أشهر : 1 000 × 6 ÷ 12 = 500 ──
    ("mois1", "وماذا لو سحب التاجر مالَه بعد ستة أشهر فقط؟ "
              "أحسب فائدة السنة كاملة أولًا، ثم آخذ نصيب الأشهر."),
    ("mois2", "فائدة ستة أشهر: ألف في ستة مقسومة على اثني عشر: خمسمائة أوقية."),
    # ── انتبه ──
    ("att1", "انتبه جيدًا! النسبة سنوية، فلا تطبقها على الأشهر مباشرة: "
             "احسب فائدة السنة كاملة أولًا ثم اقسم."),
    # ── السر ──
    ("astuce", "وقبل أن نفترق، إليكم سرًّا ذهبيًا: القاعدة تعمل في الاتجاهين! "
               "النسبة تساوي الفائدة في مائة مقسومة على رأس المال: "
               "فمن حصل على ستمائة أوقية من عشرة آلاف أوقية، فنسبته ستة في المائة."),
    ("outro", "والآن افتح كراسك وحلّ تمارين الوحدة الرابعة والعشرين. إلى اللقاء يا أبطال!"),
]

OUT = Path(__file__).parent / "audio_u24"


async def main():
    OUT.mkdir(exist_ok=True)
    ff = imageio_ffmpeg.get_ffmpeg_exe()
    durations = {}
    for name, text in SEGMENTS:
        mp3 = OUT / f"{name}.mp3"
        await edge_tts.Communicate(text, VOICE, rate=RATE).save(str(mp3))
        r = subprocess.run([ff, "-i", str(mp3), "-f", "null", "-"],
                           capture_output=True, text=True)
        for line in r.stderr.splitlines():
            if "time=" in line:
                t = line.split("time=")[1].split(" ")[0]
                h, m, s = t.split(":")
                durations[name] = round(int(h) * 3600 + int(m) * 60 + float(s), 2)
        print(f"{name}: {durations.get(name, '?')} s")
    (OUT / "durations.json").write_text(json.dumps(durations, indent=2))
    print("total:", round(sum(durations.values()), 1), "s")


if __name__ == "__main__":
    asyncio.run(main())
