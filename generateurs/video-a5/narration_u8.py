# -*- coding: utf-8 -*-
"""Narration U8 — مقارنة الأعداد الصحيحة وترتيبها. Fidèle au cahier :
الرموز > < = · عدّ الخانات أولًا · المقارنة خانة خانة من اليسار · الترتيب التصاعدي والتنازلي.
Exemples du cahier : 10 200 > 9 900 · 4 325 / 4 352 · 1 042<1 204<1 240<1 402 · 10 005 > 9 999."""
import asyncio, json, subprocess
from pathlib import Path

import edge_tts
import imageio_ffmpeg

VOICE = "ar-SA-HamedNeural"
RATE = "-3%"

SEGMENTS = [
    ("intro1", "أهلًا بكم يا أبطال الرياضيات! درسُ اليوم من الوحدة الثامنة: "
               "مقارنة الأعداد الصحيحة وترتيبها."),
    ("intro2", "سنتعلم المقارنة بالرموز: أكبر من، وأصغر من، ويساوي، "
               "ثم الترتيب التصاعدي والتنازلي."),
    # ── الرموز ──
    ("def1", "أقارن عددين معناه أن أحدّد أيهما أكبر وأيهما أصغر."),
    ("def2", "عندنا ثلاثة رموز: أكبر من، وأصغر من، ويساوي. "
             "وتذكّر: الفم المفتوح يتجه دائمًا نحو العدد الأكبر!"),
    # ── القاعدة 1 : عدّ الخانات ──
    ("meth1", "القاعدة الأولى: أعدّ الأرقام؛ العدد الذي فيه خانات أكثر هو الأكبر."),
    ("meth2", "انظر: عشرة آلاف ومئتان فيه خمس خانات، وتسعة آلاف وتسعمائة فيه أربع خانات فقط؛ "
              "إذن العدد الأول هو الأكبر!"),
    # ── القاعدة 2 : خانة خانة من اليسار : 4 325 / 4 352 ──
    ("comp1", "وإذا تساوى عدد الخانات؟ أقارن خانةً خانةً بدءًا من اليسار."),
    ("comp2", "لنقارن معًا أربعة آلاف وثلاثمائة وخمسة وعشرين، "
              "مع أربعة آلاف وثلاثمائة واثنين وخمسين."),
    ("comp3", "خانة الآلاف: أربعة يساوي أربعة. خانة المئات: ثلاثة يساوي ثلاثة. نواصل!"),
    ("comp4", "خانة العشرات: اثنان أصغر من خمسة. توقف هنا! "
              "أول خانة مختلفة تحسم المقارنة."),
    ("comp5", "إذن العدد الأول أصغر من العدد الثاني، ونكتب بينهما رمز أصغر من."),
    # ── الترتيب ──
    ("ord1", "والآن الترتيب! الترتيب التصاعدي: من الأصغر إلى الأكبر، كمن يصعد الدرج."),
    ("ord2", "لنرتب هذه الأعداد الأربعة تصاعديًا: أبحث عن الأصغر وأضعه أولًا، "
             "ثم الذي يليه، حتى أصل إلى الأكبر."),
    ("ord3", "والترتيب التنازلي هو العكس تمامًا: أبدأ بالأكبر وأنزل حتى الأصغر، "
             "كمن ينزل الدرج."),
    # ── انتبه ──
    ("att1", "انتبه جيدًا! تسعة آلاف وتسعمائة وتسعة وتسعون يبدو كبيرًا، "
             "لكن عشرة آلاف وخمسة أكبر منه، لأن فيه خمس خانات. "
             "تحقّق من عدد الخانات أولًا!"),
    # ── السر ──
    ("astuce", "وإليك سرًّا ذهبيًا: ابدأ دائمًا من اليسار؛ "
               "أول رقم مختلف يحسم المقارنة فورًا!"),
    ("outro", "والآن افتح كراسك وحلّ تمارين الوحدة الثامنة. إلى اللقاء يا أبطال!"),
]

OUT = Path(__file__).parent / "audio_u8"


async def main():
    OUT.mkdir(exist_ok=True)
    ff = imageio_ffmpeg.get_ffmpeg_exe()
    durations = {}
    for name, text in SEGMENTS:
        mp3 = OUT / f"{name}.mp3"
        await edge_tts.Communicate(text, VOICE, rate=RATE).save(str(mp3))
        r = subprocess.run([ff, "-i", str(mp3), "-f", "null", "-"],
                           capture_output=True, text=True)
        for line in r.stderr.splitlines():
            if "time=" in line:
                t = line.split("time=")[1].split(" ")[0]
                h, m, s = t.split(":")
                durations[name] = round(int(h) * 3600 + int(m) * 60 + float(s), 2)
        print(f"{name}: {durations.get(name, '?')} s")
    (OUT / "durations.json").write_text(json.dumps(durations, indent=2))
    print("total:", round(sum(durations.values()), 1), "s")


if __name__ == "__main__":
    asyncio.run(main())
