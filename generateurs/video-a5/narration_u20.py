# -*- coding: utf-8 -*-
"""Narration U20 — الزمن والأعداد الستينية. Fidèle au cahier :
1 h = 60 min = 3600 s · نظام ستيني أساسه 60 · جمع ستيني مع الحامل (1 h 50 min + 2 h 20 min = 4 h 10 min) ·
المدة = الوصول − الانطلاق (درس 9 h 15 → 11 h 40 = 2 h 25 min بالقفزات) ·
انتبه: أستلف 60 لا 100 · سر: نصف = 30 · ربع = 15 · ثلث = 20."""
import asyncio, json, subprocess
from pathlib import Path

import edge_tts
import imageio_ffmpeg

VOICE = "ar-SA-HamedNeural"
RATE = "-3%"

SEGMENTS = [
    ("intro1", "أهلًا بكم يا أبطال الرياضيات! درسُ اليوم من الوحدة العشرين: الزمن والأعداد الستينية."),
    ("intro2", "في هذا الدرس سنتعلم التحويل بين الساعات والدقائق والثواني، "
               "وسنحسب المدة بين توقيتين."),
    # ── الساعة الحائطية ──
    ("clock1", "انظروا إلى هذه الساعة: العقرب القصير يدل على الساعات، "
               "والعقرب الطويل يدل على الدقائق."),
    ("clock2", "عندما يدور العقرب الطويل دورة كاملة، تمر ستون دقيقة: أي ساعة كاملة."),
    # ── التحويلات : 1 h = 60 min = 3600 s ──
    ("conv1", "احفظ جيدًا: الساعة الواحدة تساوي ستين دقيقة، والدقيقة الواحدة تساوي ستين ثانية."),
    ("conv2", "إذن الساعة الواحدة تساوي ستين في ستين: ثلاثة آلاف وستمائة ثانية!"),
    ("conv3", "هذا نظام ستيني أساسه ستون، فلا تحسب فيه بالمئة أبدًا."),
    ("conv4", "مثال صغير: ساعتان تساويان اثنين في ستين: مئة وعشرين دقيقة."),
    # ── الجمع الستيني : 1 h 50 min + 2 h 20 min ──
    ("add1", "والآن لنجمع عددين ستينيين: ساعة وخمسون دقيقة، زائد ساعتين وعشرين دقيقة."),
    ("add2", "أجمع الدقائق أولًا: خمسون زائد عشرين: سبعون. وسبعون أكبر من ستين!"),
    ("add3", "أنزع ستين دقيقة وأحمل ساعة واحدة، فيبقى في عمود الدقائق عشر دقائق."),
    ("add4", "ثم أجمع الساعات: واحد زائد اثنين زائد الحامل واحد: أربع ساعات. "
             "فالجواب: أربع ساعات وعشر دقائق."),
    # ── حساب المدة : 9 h 15 → 11 h 40 ──
    ("dur1", "ولحساب المدة أطرح ساعة الانطلاق من ساعة الوصول: "
             "بدأ درس على التاسعة وخمس عشرة دقيقة، وانتهى على الحادية عشرة وأربعين دقيقة."),
    ("dur2", "أعدّ بالقفزات على المستقيم: ساعة، ثم ساعة، ثم خمس وعشرون دقيقة: "
             "فالمدة ساعتان وخمس وعشرون دقيقة."),
    # ── انتبه ──
    ("att1", "انتبه جيدًا! عند طرح الأعداد الستينية أستلف ستين وليس مئة: "
             "إذا نقصت الثواني آخذ دقيقة واحدة وأحوّلها إلى ستين ثانية."),
    # ── السر ──
    ("astuce", "وقبل أن نفترق، إليك سرًّا مفيدًا: نصف الساعة ثلاثون دقيقة، "
               "وربع الساعة خمس عشرة دقيقة، وثلث الساعة عشرون دقيقة. احفظها تُسرع حسابك كثيرًا!"),
    ("outro", "والآن افتح كراسك وحلّ تمارين الوحدة العشرين. إلى اللقاء يا أبطال!"),
]

OUT = Path(__file__).parent / "audio_u20"


async def main():
    OUT.mkdir(exist_ok=True)
    ff = imageio_ffmpeg.get_ffmpeg_exe()
    durations = {}
    for name, text in SEGMENTS:
        mp3 = OUT / f"{name}.mp3"
        await edge_tts.Communicate(text, VOICE, rate=RATE).save(str(mp3))
        r = subprocess.run([ff, "-i", str(mp3), "-f", "null", "-"],
                           capture_output=True, text=True)
        for line in r.stderr.splitlines():
            if "time=" in line:
                t = line.split("time=")[1].split(" ")[0]
                h, m, s = t.split(":")
                durations[name] = round(int(h) * 3600 + int(m) * 60 + float(s), 2)
        print(f"{name}: {durations.get(name, '?')} s")
    (OUT / "durations.json").write_text(json.dumps(durations, indent=2))
    print("total:", round(sum(durations.values()), 1), "s")


if __name__ == "__main__":
    asyncio.run(main())
