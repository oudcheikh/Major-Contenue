# -*- coding: utf-8 -*-
"""Narration U22 — الحركة المنتظمة. Fidèle au cahier :
السرعة المتوسطة = المسافة في ساعة واحدة (km/h) · مثلث السرعة-المسافة-الزمن (غطِّ المطلوب بإصبعك) ·
دراجة : 40 km في ساعتين ← 20 km/h · قطار الحديد 42 km/h في 1 h 40 min ← 70 km ·
انتبه : 1 h 40 min = 100 min لا 140 · سر : 60 km/h = 30 km في نصف ساعة = 1 km في الدقيقة."""
import asyncio, json, subprocess
from pathlib import Path

import edge_tts
import imageio_ffmpeg

VOICE = "ar-SA-HamedNeural"
RATE = "-3%"

SEGMENTS = [
    ("intro1", "أهلًا بكم يا أبطال الرياضيات! درسُ اليوم من الوحدة الثانية والعشرين: الحركة المنتظمة."),
    ("intro2", "في هذا الدرس سنفهم معنى السرعة المتوسطة، "
               "وسنحسب السرعة والمسافة والزمن بالقاعدة المناسبة."),
    # ── المفهوم ──
    ("conc1", "انظروا إلى هذه السيارة: إنها تقطع في كل ساعة نفس المسافة، "
              "فنقول إن حركتها منتظمة."),
    ("conc2", "السرعة المتوسطة هي المسافة المقطوعة في ساعة واحدة، "
              "ونقيسها بالكيلومتر في الساعة."),
    # ── مثال الدراجة : 40 km في ساعتين ──
    ("ex1", "لنحسب معًا: قطع راكب دراجة أربعين كيلومترًا في ساعتين كاملتين."),
    ("ex2", "سرعته إذن: أربعون على اثنين: عشرون كيلومترًا في الساعة."),
    # ── مثلث السرعة والمسافة والزمن ──
    ("tri1", "ولكي تحفظ القواعد الثلاث، ارسم مثلثًا: المسافة في الأعلى، "
             "والسرعة والزمن في الأسفل."),
    ("tri2", "غطِّ المطلوب بإصبعك يظهر لك القانون: المسافة تساوي السرعة في الزمن."),
    ("tri3", "والسرعة تساوي المسافة على الزمن، والزمن يساوي المسافة على السرعة."),
    # ── مثال القطار : 42 km/h في 1 h 40 min ──
    ("train1", "والآن مثال من بلادنا: قطار الحديد يسير بسرعة اثنين وأربعين كيلومترًا في الساعة. "
               "فما المسافة التي يقطعها في ساعة وأربعين دقيقة؟"),
    ("train2", "أحوّل الزمن أولًا إلى وحدة واحدة: ساعة وأربعون دقيقة تساوي ستين زائد أربعين: "
               "مئة دقيقة."),
    ("train3", "ثم أطبّق القاعدة: المسافة تساوي اثنين وأربعين في مئة على ستين: سبعون كيلومترًا."),
    # ── انتبه ──
    ("att1", "انتبه جيدًا! لا تخلط الوحدتين: ساعة وأربعون دقيقة ليست مئة وأربعين دقيقة، "
             "بل مئة دقيقة. حوّل دائمًا قبل الحساب."),
    # ── السر ──
    ("astuce", "وقبل أن نفترق، إليك سرًّا مفيدًا: السرعة ستون كيلومترًا في الساعة تعني "
               "ثلاثين كيلومترًا في نصف ساعة، وكيلومترًا واحدًا في كل دقيقة!"),
    ("outro", "والآن افتح كراسك وحلّ تمارين الوحدة الثانية والعشرين. إلى اللقاء يا أبطال!"),
]

OUT = Path(__file__).parent / "audio_u22"


async def main():
    OUT.mkdir(exist_ok=True)
    ff = imageio_ffmpeg.get_ffmpeg_exe()
    durations = {}
    for name, text in SEGMENTS:
        mp3 = OUT / f"{name}.mp3"
        await edge_tts.Communicate(text, VOICE, rate=RATE).save(str(mp3))
        r = subprocess.run([ff, "-i", str(mp3), "-f", "null", "-"],
                           capture_output=True, text=True)
        for line in r.stderr.splitlines():
            if "time=" in line:
                t = line.split("time=")[1].split(" ")[0]
                h, m, s = t.split(":")
                durations[name] = round(int(h) * 3600 + int(m) * 60 + float(s), 2)
        print(f"{name}: {durations.get(name, '?')} s")
    (OUT / "durations.json").write_text(json.dumps(durations, indent=2))
    print("total:", round(sum(durations.values()), 1), "s")


if __name__ == "__main__":
    asyncio.run(main())
