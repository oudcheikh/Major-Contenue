# -*- coding: utf-8 -*-
"""Narration U18 — الضرب في 10 و100 و1000. Fidèle au cahier (unites_4.py u18) :
عدد صحيح : أضيف الأصفار · عدد عشري : أنقل الفاصلة نحو اليمين ·
إذا نقصت الأرقام أضيف أصفارًا · مثال مصنع انواكشوط : 2,4×100=240 م ·
1,25×1000=1250 · انتبه : 0,04×100=4 وليس 0,0004."""
import asyncio, json, subprocess
from pathlib import Path

import edge_tts
import imageio_ffmpeg

VOICE = "ar-SA-HamedNeural"
RATE = "-3%"

SEGMENTS = [
    ("intro1", "أهلًا بكم يا أبطال الرياضيات! درسُ اليوم من الوحدة الثامنة عشرة: "
               "الضرب في عشرة ومئة وألف."),
    ("intro2", "في هذا الدرس سنتعلم الضرب في عشرة ومئة وألف بسرعة البرق، "
               "دون وضع العملية ودون آلة حاسبة!"),
    # ── العدد الصحيح : أضيف الأصفار ──
    ("ent1", "نبدأ بالعدد الصحيح: لأضربه في عشرة أضيف على يمينه صفرًا واحدًا، "
             "وفي مئة صفرين، وفي ألف ثلاثة أصفار."),
    ("ent2", "انظروا: خمسة وأربعون في عشرة: أربعمئة وخمسون. "
             "وثلاثمئة وسبعة في مئة: ثلاثون ألفًا وسبعمئة."),
    # ── العدد العشري : أنقل الفاصلة ──
    ("dec1", "وأما العدد العشري ففيه فاصلة، والفاصلة تحب القفز! "
             "لأضرب في عشرة أنقلها رقمًا واحدًا نحو اليمين."),
    ("dec2", "وفي مئة أنقلها رقمين، وفي ألف ثلاثة أرقام: "
             "عدد الأصفار يساوي عدد القفزات."),
    ("dec3", "مثال: اثنان فاصلة أربعة في مئة: أنقل الفاصلة قفزتين نحو اليمين: "
             "مئتان وأربعون!"),
    ("dec4", "وإذا لم تكفِ الأرقام؟ أضيف أصفارًا على اليمين: "
             "واحد فاصلة خمسة وعشرون في ألف: ألف ومئتان وخمسون."),
    # ── مثال من الحياة : مصنع الملابس ──
    ("app1", "مثال من انواكشوط: مصنع ملابس يحتاج لكل فستان مترين وربع من القماش، "
             "والطلبية ألف فستان. كم مترًا يلزم؟"),
    ("app2", "اثنان فاصلة مئتان وخمس وعشرون في ألف: أنقل الفاصلة ثلاث قفزات: "
             "ألفان ومئتان وخمس وعشرون مترًا. أسرع بكثير من وضع العملية عموديًا!"),
    # ── انتبه ──
    ("att1", "انتبه جيدًا! عند الضرب تنتقل الفاصلة نحو اليمين لا نحو اليسار: "
             "صفر فاصلة صفر أربعة في مئة تساوي أربعة، وليس صفرًا فاصلة أصفار!"),
    # ── السر ──
    ("astuce", "وقبل أن نفترق، إليك سرًّا ذهبيًا: قبل أن تقفز الفاصلة، "
               "عُدَّ أصفار العدد: في عشرة قفزة، وفي مئة قفزتان، وفي ألف ثلاث قفزات. "
               "عدّ الأصفار ثم اقفز!"),
    ("outro", "والآن افتح كراسك وحلّ تمارين الوحدة الثامنة عشرة. إلى اللقاء يا أبطال!"),
]

OUT = Path(__file__).parent / "audio_u18"


async def main():
    OUT.mkdir(exist_ok=True)
    ff = imageio_ffmpeg.get_ffmpeg_exe()
    durations = {}
    for name, text in SEGMENTS:
        mp3 = OUT / f"{name}.mp3"
        await edge_tts.Communicate(text, VOICE, rate=RATE).save(str(mp3))
        r = subprocess.run([ff, "-i", str(mp3), "-f", "null", "-"],
                           capture_output=True, text=True)
        for line in r.stderr.splitlines():
            if "time=" in line:
                t = line.split("time=")[1].split(" ")[0]
                h, m, s = t.split(":")
                durations[name] = round(int(h) * 3600 + int(m) * 60 + float(s), 2)
        print(f"{name}: {durations.get(name, '?')} s")
    (OUT / "durations.json").write_text(json.dumps(durations, indent=2))
    print("total:", round(sum(durations.values()), 1), "s")


if __name__ == "__main__":
    asyncio.run(main())
