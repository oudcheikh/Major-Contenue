# -*- coding: utf-8 -*-
"""Narration U5 — القسمة. Fidèle au cahier :
التوزيع بالتساوي · المقسوم/المقسوم عليه/خارج القسمة · أبحث في جدول الضرب · القسمة مع الباقي.
Exemples du cahier : 12÷3=4 (تمرات وأطباق) · 3×4=12 · 14÷3=4 والباقي 2 · 12÷2 ≠ 2÷12."""
import asyncio, json, subprocess
from pathlib import Path

import edge_tts
import imageio_ffmpeg

VOICE = "ar-SA-HamedNeural"
RATE = "-3%"

SEGMENTS = [
    ("intro1", "أهلًا بكم يا أبطال الرياضيات! درسُ اليوم من الوحدة الخامسة: القسمة."),
    ("intro2", "في هذا الدرس سنفهم القسمة على أنها توزيع بالتساوي، "
               "وسنستعمل جداول الضرب لنجد خارج القسمة، وسنحسب القسمة مع الباقي."),
    # ── التوزيع بالتساوي : 12 ÷ 3 ──
    ("def1", "القسمة تُستعمل للتوزيع إلى حصص متساوية. "
             "انظروا: عندنا اثنتا عشرة تمرة وثلاثة أطباق."),
    ("dist1", "لنوزّع بالتساوي: تمرة لكل طبق، ثم تمرة لكل طبق، حتى تنتهي التمرات كلها."),
    ("dist2", "انتهى التوزيع! في كل طبق أربع تمرات، والحصص كلها متساوية."),
    ("def2", "نكتب: اثنا عشر مقسومًا على ثلاثة يساوي أربعة. "
             "اثنا عشر هو المقسوم، وثلاثة هو المقسوم عليه، وأربعة هو خارج القسمة."),
    # ── الطريقة : أبحث في جدول الضرب ──
    ("mult1", "وكيف أجد خارج القسمة بسرعة؟ أطرح السؤال: ثلاثة في كم يساوي اثني عشر؟"),
    ("mult2", "أبحث في جدول الثلاثة: ثلاثة في أربعة يساوي اثني عشر. إذن الخارج هو أربعة!"),
    # ── القسمة مع الباقي : 14 ÷ 3 ──
    ("rem1", "لكن أحيانًا لا تكون القسمة تامة. لنوزّع أربع عشرة تمرة على ثلاثة أطباق."),
    ("rem2", "أعطي كل طبق أربع تمرات، فأكون قد وزّعت اثنتي عشرة تمرة، "
             "وتبقى تمرتان خارج الأطباق."),
    ("rem3", "هاتان التمرتان هما الباقي. "
             "نكتب: أربعة عشر مقسومًا على ثلاثة يساوي أربعة والباقي اثنان."),
    ("rem4", "وللتحقق: ثلاثة في أربعة يساوي اثني عشر، "
             "واثنا عشر زائد اثنين يساوي أربعة عشر. حسابُنا صحيح!"),
    # ── انتبه ──
    ("att1", "انتبه جيدًا! الترتيب مهم في القسمة: "
             "اثنا عشر مقسومًا على اثنين لا يساوي اثنين مقسومًا على اثني عشر."),
    # ── السر ──
    ("astuce", "وقبل أن نفترق، إليك سرًّا صغيرًا: كل عدد مقسوم على واحد يبقى كما هو، "
               "وكل عدد مقسوم على نفسه يساوي واحدًا."),
    ("outro", "والآن افتح كراسك وحلّ تمارين الوحدة الخامسة. إلى اللقاء يا أبطال!"),
]

OUT = Path(__file__).parent / "audio_u5"


async def main():
    OUT.mkdir(exist_ok=True)
    ff = imageio_ffmpeg.get_ffmpeg_exe()
    durations = {}
    for name, text in SEGMENTS:
        mp3 = OUT / f"{name}.mp3"
        await edge_tts.Communicate(text, VOICE, rate=RATE).save(str(mp3))
        r = subprocess.run([ff, "-i", str(mp3), "-f", "null", "-"],
                           capture_output=True, text=True)
        for line in r.stderr.splitlines():
            if "time=" in line:
                t = line.split("time=")[1].split(" ")[0]
                h, m, s = t.split(":")
                durations[name] = round(int(h) * 3600 + int(m) * 60 + float(s), 2)
        print(f"{name}: {durations.get(name, '?')} s")
    (OUT / "durations.json").write_text(json.dumps(durations, indent=2))
    print("total:", round(sum(durations.values()), 1), "s")


if __name__ == "__main__":
    asyncio.run(main())
