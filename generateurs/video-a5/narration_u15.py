# -*- coding: utf-8 -*-
"""Narration U15 — النسب المئوية. Fidèle au cahier (unites_3.py u15) :
«من 100» · 50% = النصف، 25% = الربع، 10% = العُشر · الطريقة (أضرب في النسبة ثم أقسم على 100) ·
مثال الكراس 50% من 200 = 100 · مسألة الكراس: كرة بـ80 أوقية تخفيض 25% ·
انتبه: قيمة التخفيض ليست الثمن الجديد · السر: الاختصارات السريعة."""
import asyncio, json, subprocess
from pathlib import Path

import edge_tts
import imageio_ffmpeg

VOICE = "ar-SA-HamedNeural"
RATE = "-3%"

SEGMENTS = [
    ("intro1", "أهلًا بكم من جديد يا أبطال الرياضيات! درسُ اليوم من الوحدة الخامسة عشرة: النسب المئوية."),
    ("intro2", "في هذا الدرس سنفهم معنى النسبة المئوية، وسنحسب نسبة مئوية من عدد، "
               "ونحل مسائل التخفيض من الحياة اليومية."),
    # ── المفهوم : «من مئة» على الشريط ──
    ("def1", "النسبة المئوية هي طريقة لقول: من مئة. انظروا إلى هذا الشريط: "
             "إنه يمثل مئة خانة، وكل حصة فيه عشر خانات، أي عشرة في المئة."),
    ("def2", "وإذا لوّنا خمس حصص، فقد لوّنا خمسين خانة من مئة: "
             "خمسون في المئة، أي النصف!"),
    ("def3", "وخمسة وعشرون في المئة تعني خمسة وعشرين من مئة: إنها الربع!"),
    # ── الطريقة ──
    ("meth1", "كيف أحسب نسبة مئوية من عدد؟ خطوتان فقط: "
              "أضرب العدد في النسبة، ثم أقسم الناتج على مئة."),
    # ── مثال الكراس : 50% من 200 ──
    ("calc1", "مثال من كراسنا: كم يساوي خمسون في المئة من مئتين؟ "
              "أضرب مئتين في خمسين، ثم أقسم الناتج على مئة: الجواب مئة."),
    ("calc2", "ولنتحقق: خمسون في المئة هي النصف، ونصف المئتين هو مئة. الحسابان متفقان!"),
    # ── مسألة التخفيض : كرة 80 أوقية، 25% ──
    ("prob1", "والآن مسألة من السوق: كرة ثمنها ثمانون أوقية، "
              "عليها تخفيض بنسبة خمسة وعشرين في المئة. ما قيمة التخفيض؟"),
    ("prob2", "أضرب ثمانين في خمسة وعشرين، ثم أقسم على مئة: قيمة التخفيض عشرون أوقية."),
    # ── انتبه ──
    ("att1", "انتبه جيدًا! قيمة التخفيض ليست الثمن الجديد: "
             "الثمن الجديد يساوي الثمن القديم ناقص قيمة التخفيض."),
    ("att2", "ثمانون ناقص عشرين يساوي ستين: الثمن الجديد للكرة ستون أوقية."),
    # ── السر ──
    ("astuce", "وقبل أن نفترق، إليك اختصارات سريعة: خمسون في المئة هي النصف، "
               "وخمسة وعشرون في المئة هي الربع، وعشرة في المئة هي القسمة على عشرة!"),
    ("outro", "والآن افتح كراسك وحلّ تمارين الوحدة الخامسة عشرة. إلى اللقاء يا أبطال!"),
]

OUT = Path(__file__).parent / "audio_u15"


async def main():
    OUT.mkdir(exist_ok=True)
    ff = imageio_ffmpeg.get_ffmpeg_exe()
    durations = {}
    for name, text in SEGMENTS:
        mp3 = OUT / f"{name}.mp3"
        await edge_tts.Communicate(text, VOICE, rate=RATE).save(str(mp3))
        r = subprocess.run([ff, "-i", str(mp3), "-f", "null", "-"],
                           capture_output=True, text=True)
        for line in r.stderr.splitlines():
            if "time=" in line:
                t = line.split("time=")[1].split(" ")[0]
                h, m, s = t.split(":")
                durations[name] = round(int(h) * 3600 + int(m) * 60 + float(s), 2)
        print(f"{name}: {durations.get(name, '?')} s")
    (OUT / "durations.json").write_text(json.dumps(durations, indent=2))
    print("total:", round(sum(durations.values()), 1), "s")


if __name__ == "__main__":
    asyncio.run(main())
