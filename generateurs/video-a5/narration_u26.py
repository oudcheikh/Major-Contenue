# -*- coding: utf-8 -*-
"""Narration U26 — الكتلة القائمة والصافية والفارغ. Fidèle au cahier (u26_p1..p3) :
القائمة = المنتوج + الغلاف · الصافية = المنتوج وحده · الفارغ = الغلاف وحده ·
العلاقات الثلاث · توحيد الوحدات قبل الطرح.
Exemples du cahier : عسل 1,2 kg − 200 g = 1 000 g · انتبه 5 kg − 500 g = 4 500 g."""
import asyncio, json, subprocess
from pathlib import Path

import edge_tts
import imageio_ffmpeg

VOICE = "ar-SA-HamedNeural"
RATE = "-3%"

SEGMENTS = [
    ("intro1", "أهلًا بكم يا أبطال الرياضيات! درسُ اليوم من الوحدة السادسة والعشرين: "
               "الكتلة القائمة والكتلة الصافية والفارغ."),
    ("intro2", "في هذا الدرس سنميّز بين الكتلة القائمة والكتلة الصافية والفارغ، "
               "وسنستعمل العلاقات الثلاث بينها، دون أن ننسى توحيد الوحدات قبل الحساب."),
    # ── القارورة : منتوج + غلاف ──
    ("jar1", "انظروا إلى هذه القارورة المملوءة بالعسل: فيها المنتوج وهو العسل، "
             "وفيها الغلاف وهو القارورة نفسها."),
    ("jar2", "الكتلة القائمة هي كتلة المنتوج مع غلافه معًا، أي القارورة وهي مملوءة."),
    ("jar3", "الكتلة الصافية هي كتلة المنتوج وحده، والفارغ هو كتلة الغلاف وحده."),
    # ── القواعد الثلاث ──
    ("form1", "القاعدة الأولى: الكتلة القائمة تساوي الكتلة الصافية زائد الفارغ."),
    ("form2", "ومنها نستخرج قاعدتين: الكتلة الصافية تساوي القائمة ناقص الفارغ، "
              "والفارغ يساوي القائمة ناقص الصافية."),
    # ── مثال العسل : 1,2 kg − 200 g ──
    ("ex1", "لنطبّق معًا: قارورة عسل كتلتها القائمة كيلوغرام واحد ومئتا غرام، "
            "وفارغها مئتا غرام."),
    ("ex2", "أوحّد الوحدتين أولًا: كيلوغرام واحد ومئتا غرام تساوي ألفًا ومئتي غرام."),
    ("ex3", "ثم أطرح: ألف ومئتان ناقص مئتين يساوي ألف غرام، "
            "أي كيلوغرامًا واحدًا من العسل الصافي."),
    # ── انتبه ──
    ("att1", "انتبه جيدًا! وحّد الوحدتين قبل الطرح: خمسة كيلوغرامات ناقص خمسمائة غرام "
             "تصبح خمسة آلاف غرام ناقص خمسمائة غرام، والنتيجة أربعة آلاف وخمسمائة غرام."),
    # ── السر ──
    ("astuce", "وقبل أن نفترق، إليك سرًّا ذهبيًا: الكتلة القائمة أكبر دائمًا من الكتلة الصافية، "
               "فإذا وجدت كتلة صافية أكبر من القائمة فراجع حسابك فورًا!"),
    ("outro", "والآن افتح كراسك وحلّ تمارين الوحدة السادسة والعشرين. إلى اللقاء يا أبطال!"),
]

OUT = Path(__file__).parent / "audio_u26"


async def main():
    OUT.mkdir(exist_ok=True)
    ff = imageio_ffmpeg.get_ffmpeg_exe()
    durations = {}
    for name, text in SEGMENTS:
        mp3 = OUT / f"{name}.mp3"
        await edge_tts.Communicate(text, VOICE, rate=RATE).save(str(mp3))
        r = subprocess.run([ff, "-i", str(mp3), "-f", "null", "-"],
                           capture_output=True, text=True)
        for line in r.stderr.splitlines():
            if "time=" in line:
                t = line.split("time=")[1].split(" ")[0]
                h, m, s = t.split(":")
                durations[name] = round(int(h) * 3600 + int(m) * 60 + float(s), 2)
        print(f"{name}: {durations.get(name, '?')} s")
    (OUT / "durations.json").write_text(json.dumps(durations, indent=2))
    print("total:", round(sum(durations.values()), 1), "s")


if __name__ == "__main__":
    asyncio.run(main())
