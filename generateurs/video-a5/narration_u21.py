# -*- coding: utf-8 -*-
"""Narration U21 — التناسبية. Fidèle au cahier :
مقداران متناسبان = الضرب في نفس العدد · جدول التناسبية بمعامل الضرب ·
مثال الكاهية : 5 خبزات = 75 أوقية ← 3 خبزات = 45 · 11 خبزة = 165 ·
القاعدة الثلاثية : 4 أمتار ملحفة = 480 أوقية ← 7 أمتار = 840 ·
انتبه : العمر والطول لا يتناسبان · سر : ثمن الوحدة الواحدة."""
import asyncio, json, subprocess
from pathlib import Path

import edge_tts
import imageio_ffmpeg

VOICE = "ar-SA-HamedNeural"
RATE = "-3%"

SEGMENTS = [
    ("intro1", "أهلًا بكم يا أبطال الرياضيات! درسُ اليوم من الوحدة الحادية والعشرين: التناسبية."),
    ("intro2", "في هذا الدرس سنتعرف المقادير المتناسبة، "
               "وسنتعلم إكمال جدول التناسبية واستعمال القاعدة الثلاثية."),
    # ── التعريف ──
    ("def1", "مقداران متناسبان إذا انتقلنا من أحدهما إلى الآخر بالضرب في نفس العدد دائمًا."),
    # ── جدول التناسبية : الخبزات ──
    ("tab1", "إليكم مثالًا من السوق: خمس خبزات ثمنها خمس وسبعون أوقية. "
             "فما ثمن ثلاث خبزات؟ وما ثمن إحدى عشرة خبزة؟"),
    ("tab2", "أنظّم المعطيات في جدول التناسبية: في السطر الأول عدد الخبزات، "
             "وفي السطر الثاني الثمن بالأوقية."),
    ("tab3", "للانتقال من السطر الأول إلى السطر الثاني أضرب في نفس العدد: "
             "خمس وسبعون على خمسة: خمسة عشر."),
    ("tab4", "خمسة عشر هو ثمن الخبزة الواحدة: نسميه معامل الضرب."),
    ("tab5", "إذن ثمن ثلاث خبزات: ثلاثة في خمسة عشر: خمس وأربعون أوقية."),
    ("tab6", "وثمن إحدى عشرة خبزة: أحد عشر في خمسة عشر: مئة وخمس وستون أوقية."),
    # ── القاعدة الثلاثية : قماش الملحفة ──
    ("regle1", "وهناك طريقة ذهبية أخرى نسميها القاعدة الثلاثية: "
               "أنظّم المعطيات الثلاثة في جدول، ثم أضرب، ثم أقسم."),
    ("regle2", "اشترت أم سلمة أربعة أمتار من قماش الملحفة بأربعمائة وثمانين أوقية. "
               "فما ثمن سبعة أمتار؟"),
    ("regle3", "أضرب العددين المتقاطعين المعلومين: أربعمائة وثمانون في سبعة: "
               "ثلاثة آلاف وثلاثمائة وستون."),
    ("regle4", "ثم أقسم الناتج على العدد الثالث: ثلاثة آلاف وثلاثمائة وستون على أربعة: "
               "ثمانمائة وأربعون أوقية."),
    # ── انتبه ──
    ("att1", "انتبه جيدًا! ليس كل شيء متناسبًا: عمر الطفل وطوله لا يتناسبان، "
             "ففي اثنتي عشرة سنة لا يكون طولك ضعف طولك في ست سنوات."),
    # ── السر ──
    ("astuce", "وقبل أن نفترق، إليك سرًّا مفيدًا: ابحث أولًا عن ثمن الوحدة الواحدة، "
               "فإذا عرفت ثمن القطعة الواحدة سهُل عليك كل شيء!"),
    ("outro", "والآن افتح كراسك وحلّ تمارين الوحدة الحادية والعشرين. إلى اللقاء يا أبطال!"),
]

OUT = Path(__file__).parent / "audio_u21"


async def main():
    OUT.mkdir(exist_ok=True)
    ff = imageio_ffmpeg.get_ffmpeg_exe()
    durations = {}
    for name, text in SEGMENTS:
        mp3 = OUT / f"{name}.mp3"
        await edge_tts.Communicate(text, VOICE, rate=RATE).save(str(mp3))
        r = subprocess.run([ff, "-i", str(mp3), "-f", "null", "-"],
                           capture_output=True, text=True)
        for line in r.stderr.splitlines():
            if "time=" in line:
                t = line.split("time=")[1].split(" ")[0]
                h, m, s = t.split(":")
                durations[name] = round(int(h) * 3600 + int(m) * 60 + float(s), 2)
        print(f"{name}: {durations.get(name, '?')} s")
    (OUT / "durations.json").write_text(json.dumps(durations, indent=2))
    print("total:", round(sum(durations.values()), 1), "s")


if __name__ == "__main__":
    asyncio.run(main())
