# -*- coding: utf-8 -*-
"""Narration U17 — الكسور المتكافئة وجمع الكسور. Fidèle au cahier :
1/2=2/4=3/6 · نضرب/نقسم البسط والمقام في نفس العدد · جمع نفس المقام (2/5+1/5) ·
توحيد المقامات (2/3+3/4=17/12) · كسر من عدد (200×2÷5=80) · لا نجمع المقامين أبدًا."""
import asyncio, json, subprocess
from pathlib import Path

import edge_tts
import imageio_ffmpeg

VOICE = "ar-SA-HamedNeural"
RATE = "-3%"

SEGMENTS = [
    ("intro1", "أهلًا بكم يا أبطال الرياضيات! درسُ اليوم من الوحدة السابعة عشرة: "
               "الكسور المتكافئة وجمع الكسور."),
    ("intro2", "في هذا الدرس سنتعرف الكسور المتكافئة، وسنجمع الكسور ونطرحها، "
               "وسنأخذ كسرًا من عدد لحل مسائل الشراء."),
    # ── التكافؤ : نفس المساحة الملونة ──
    ("eq1", "انظروا إلى هذا القرص: قسمته إلى حصتين متساويتين ولوّنت واحدة: هذا هو النصف."),
    ("eq2", "وهذا قرص آخر بنفس الحجم: قسمته إلى أربع حصص ولوّنت اثنتين: اثنان على أربعة."),
    ("eq3", "تأملوا جيدًا: المساحة الملوّنة واحدة في القرصين! "
            "إذن النصف يساوي اثنين على أربعة: نقول إن الكسرين متكافئان."),
    # ── القاعدة : ×2/×2 ──
    ("eq4", "وإليكم القاعدة: للحصول على كسر مكافئ، أضرب البسط والمقام في نفس العدد."),
    ("eq5", "انظروا: واحد في اثنين يساوي اثنين، واثنان في اثنين يساوي أربعة: "
            "هكذا تحوّل النصف إلى اثنين على أربعة."),
    ("simp1", "والتبسيط هو الطريق المعاكس: أقسم البسط والمقام على نفس العدد: "
              "ستة على تسعة، أقسم على ثلاثة، فأحصل على اثنين على ثلاثة."),
    # ── الجمع : نفس المقام ──
    ("add1", "والآن جمع الكسور. إذا كان للكسرين نفس المقام، أجمع البسطين فقط، "
             "أو أطرحهما، وأحتفظ بالمقام كما هو."),
    ("add2", "خُمسان زائد خُمس واحد يساوي ثلاثة أخماس. "
             "انظروا إلى الشريط كيف امتلأت ثلاث حصص من خمس!"),
    # ── مقامان مختلفان ──
    ("diff1", "وإذا اختلف المقامان؟ لا أجمع مباشرة أبدًا! "
              "أبحث أولًا عن كسرين متكافئين لهما نفس المقام."),
    ("diff2", "ثلثان زائد ثلاثة أرباع: أوحّد المقامين إلى اثني عشر، فيصبح الجمع: "
              "ثمانية على اثني عشر زائد تسعة على اثني عشر يساوي سبعة عشر على اثني عشر."),
    # ── كسر من عدد ──
    ("fract1", "بقي سؤال مهم: كيف آخذ كسرًا من عدد؟ الطريقة سهلة: "
               "أضرب العدد في البسط ثم أقسم على المقام."),
    ("fract2", "مع المختار مئتا أوقية، أعطى صديقه خُمسيها: "
               "مئتان في اثنين تقسيم خمسة يساوي ثمانين أوقية."),
    # ── انتبه ──
    ("att1", "انتبه جيدًا! عند جمع كسرين لا أجمع المقامين أبدًا: "
             "ربع زائد ربعين يساوي ثلاثة أرباع، وليس ثلاثة أثمان!"),
    # ── السر ──
    ("astuce", "وقبل أن نفترق، إليك سرًّا صغيرًا: الكسر لا يتغير إذا ضربتَ بسطه ومقامه "
               "في نفس العدد، كأنك تقطّع نفس الكعكة إلى قطع أصغر!"),
    ("outro", "والآن افتح كراسك وحلّ تمارين الوحدة السابعة عشرة. إلى اللقاء يا أبطال!"),
]

OUT = Path(__file__).parent / "audio_u17"


async def main():
    OUT.mkdir(exist_ok=True)
    ff = imageio_ffmpeg.get_ffmpeg_exe()
    durations = {}
    for name, text in SEGMENTS:
        mp3 = OUT / f"{name}.mp3"
        await edge_tts.Communicate(text, VOICE, rate=RATE).save(str(mp3))
        r = subprocess.run([ff, "-i", str(mp3), "-f", "null", "-"],
                           capture_output=True, text=True)
        for line in r.stderr.splitlines():
            if "time=" in line:
                t = line.split("time=")[1].split(" ")[0]
                h, m, s = t.split(":")
                durations[name] = round(int(h) * 3600 + int(m) * 60 + float(s), 2)
        print(f"{name}: {durations.get(name, '?')} s")
    (OUT / "durations.json").write_text(json.dumps(durations, indent=2))
    print("total:", round(sum(durations.values()), 1), "s")


if __name__ == "__main__":
    asyncio.run(main())
