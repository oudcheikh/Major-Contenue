# -*- coding: utf-8 -*-
"""Narration U9 — الكتل. Fidèle au cahier :
g/kg/t/القنطار · الميزان ذو الكفتين (1 kg = 1 000 g) · جدول التحويل (3 kg = 3 000 g) ·
مسألة الشريط (4 × 250 g = 1 kg) · انتبه: لا تجمع وحدتين مختلفتين (850 g + 1,25 kg) ·
السر: الطن = 10 قناطير."""
import asyncio, json, subprocess
from pathlib import Path

import edge_tts
import imageio_ffmpeg

VOICE = "ar-SA-HamedNeural"
RATE = "-3%"

SEGMENTS = [
    ("intro1", "أهلًا بكم يا أبطال الرياضيات! درسُ اليوم من الوحدة التاسعة: الكتل."),
    ("intro2", "سنتعرف وحدات الكتلة: الغرام والكيلوغرام والطن والقنطار، "
               "وسنتعلم التحويل بينها."),
    # ── الميزان ──
    ("def1", "الكتلة تخبرنا كم يزن الجسم، ولقياسها نستعمل الميزان."),
    ("def2", "انظر إلى الميزان ذي الكفتين: كيلوغرام واحد في كفة، "
             "وألف غرام في الكفة الأخرى، والميزان متوازن تمامًا!"),
    # ── الوحدات ──
    ("unit1", "لقياس الكتل ثلاث وحدات مشهورة: الغرام، والكيلوغرام، والطن."),
    ("unit2", "الغرام للأشياء الخفيفة كملعقة السكر، والكيلوغرام هو الوحدة الرئيسية، "
              "والطن للأشياء الثقيلة كالشاحنة."),
    ("rel1", "احفظ معي: الكيلوغرام ألف غرام، والطن ألف كيلوغرام، "
             "والقنطار مئة كيلوغرام."),
    # ── جدول التحويل : 3 kg → 3 000 g ──
    ("conv1", "لنحوّل معًا ثلاثة كيلوغرامات إلى الغرام باستعمال جدول التحويل."),
    ("conv2", "أضع ثلاثة في خانة الكيلوغرام، ثم أملأ كل خانة بعدها بصفر "
              "حتى أصل إلى خانة الغرام."),
    ("conv3", "من الكيلوغرام إلى الغرام ثلاث درجات في السلم، فأضرب في ألف: "
              "ثلاثة كيلوغرامات تساوي ثلاثة آلاف غرام!"),
    # ── مسألة الشريط : 4 × 250 g ──
    ("prob1", "مسألة صغيرة: اشترى أحمد أربع خبزات، كتلة كل واحدة مئتان وخمسون غرامًا. "
              "ما الكتلة الكلية؟"),
    ("prob2", "أرسم شريطًا من أربع حصص متساوية: أربعة في مئتين وخمسين "
              "يساوي ألف غرام، أي كيلوغرام واحد بالضبط!"),
    # ── انتبه ──
    ("att1", "انتبه جيدًا! لا تجمع الغرامات مع الكيلوغرامات مباشرة. "
             "حوّل أولًا إلى الوحدة نفسها: كيلوغرام وربع يساوي ألفًا ومئتين وخمسين غرامًا، "
             "ثم أجمع مع ثمانمائة وخمسين غرامًا فأجد ألفين ومئة غرام."),
    # ── السر ──
    ("astuce", "وإليك سرًّا ذهبيًا: الطن عشرة قناطير كاملة، لأن القنطار مئة كيلوغرام، "
               "وعشر مرات مئة تساوي ألف كيلوغرام!"),
    ("outro", "والآن افتح كراسك وحلّ تمارين الوحدة التاسعة. إلى اللقاء يا أبطال!"),
]

OUT = Path(__file__).parent / "audio_u9"


async def main():
    OUT.mkdir(exist_ok=True)
    ff = imageio_ffmpeg.get_ffmpeg_exe()
    durations = {}
    for name, text in SEGMENTS:
        mp3 = OUT / f"{name}.mp3"
        await edge_tts.Communicate(text, VOICE, rate=RATE).save(str(mp3))
        r = subprocess.run([ff, "-i", str(mp3), "-f", "null", "-"],
                           capture_output=True, text=True)
        for line in r.stderr.splitlines():
            if "time=" in line:
                t = line.split("time=")[1].split(" ")[0]
                h, m, s = t.split(":")
                durations[name] = round(int(h) * 3600 + int(m) * 60 + float(s), 2)
        print(f"{name}: {durations.get(name, '?')} s")
    (OUT / "durations.json").write_text(json.dumps(durations, indent=2))
    print("total:", round(sum(durations.values()), 1), "s")


if __name__ == "__main__":
    asyncio.run(main())
