# -*- coding: utf-8 -*-
"""Narration U31 — المجسمات والحجوم والسعات. Fidèle au cahier :
المكعب (6 أوجه، 12 حرفًا، 8 رؤوس) · متوازي المستطيلات (الطول × العرض × الارتفاع) ·
m³ : ثلاثة أرقام لكل وحدة · 1 m³ = 1000 dm³ · العلاقة الذهبية 1 L = 1 dm³ ·
مثال الكراس : خزان 3 × 2 × 1 = 6 m³ = 6000 لتر."""
import asyncio, json, subprocess
from pathlib import Path

import edge_tts
import imageio_ffmpeg

VOICE = "ar-SA-HamedNeural"
RATE = "-3%"

SEGMENTS = [
    ("intro1", "أهلًا بكم يا أبطال الرياضيات! درسُ اليوم من الوحدة الحادية والثلاثين: "
               "المجسمات والحجوم والسعات."),
    ("intro2", "في هذا الدرس سنتعرف على المكعب ومتوازي المستطيلات، وسنحسب الحجوم، "
               "ونكتشف العلاقة الذهبية بين اللتر والديسيمتر المكعب."),
    # ── المجسمات ──
    ("sol1", "هذا هو المكعب: له ستة أوجه مربعة متساوية، واثنا عشر حرفًا، وثمانية رؤوس."),
    ("sol2", "وهذا متوازي المستطيلات: له ستة أوجه مستطيلة، "
             "وأبعاده ثلاثة: الطول والعرض والارتفاع."),
    ("sol3", "ومن المجسمات أيضًا: الأسطوانة ولها قاعدتان قرصيتان متوازيتان، "
             "والكرة وكل نقاط سطحها تبعد عن المركز بنفس المسافة."),
    # ── الحجوم ──
    ("vol1", "حجم المكعب نحسبه هكذا: الحرف في الحرف في الحرف. "
             "مكعب حرفه سنتيمتران: اثنان في اثنين في اثنين: ثمانية سنتيمترات مكعبة."),
    ("vol2", "وحجم متوازي المستطيلات: الطول في العرض في الارتفاع."),
    ("unit1", "الوحدة الرئيسية لقياس الحجوم هي المتر المكعب، "
              "وفي جدول الحجوم لكل وحدة ثلاث خانات، أي ثلاثة أرقام: "
              "المتر المكعب الواحد يساوي ألف ديسيمتر مكعب."),
    # ── السعات ──
    ("cap1", "أما السعات فوحدتها اللتر: به نقيس الماء والحليب والزيت. "
             "اللتر الواحد يساوي مائة سنتيلتر، أي ألف مليلتر."),
    ("gold1", "والآن العلاقة الذهبية، احفظها جيدًا: اللتر الواحد يساوي ديسيمترًا مكعبًا واحدًا. "
              "وبالتالي: المتر المكعب الواحد يساوي ألف لتر."),
    # ── مثال الكراس : خزان 3 × 2 × 1 ──
    ("ex1", "لنطبّق معًا: خزان ماء طوله ثلاثة أمتار، وعرضه متران، وارتفاعه متر واحد. "
            "الحجم يساوي ثلاثة في اثنين في واحد: ستة أمتار مكعبة."),
    ("ex2", "وستة أمتار مكعبة تساوي ستة آلاف ديسيمتر مكعب: "
            "إذن الخزان يسع ستة آلاف لتر من الماء!"),
    # ── انتبه ──
    ("att1", "انتبه جيدًا! الحجم هو ضرب الأبعاد الثلاثة، وليس جمعها!"),
    # ── السر ──
    ("astuce", "وقبل أن نفترق، إليك سرًّا ذهبيًا: في جدول المساحات رقمان لكل عمود، "
               "أما في جدول الحجوم فثلاثة أرقام لكل عمود!"),
    ("outro", "والآن افتح كراسك وحلّ تمارين الوحدة الحادية والثلاثين. إلى اللقاء يا أبطال!"),
]

OUT = Path(__file__).parent / "audio_u31"


async def main():
    OUT.mkdir(exist_ok=True)
    ff = imageio_ffmpeg.get_ffmpeg_exe()
    durations = {}
    for name, text in SEGMENTS:
        mp3 = OUT / f"{name}.mp3"
        await edge_tts.Communicate(text, VOICE, rate=RATE).save(str(mp3))
        r = subprocess.run([ff, "-i", str(mp3), "-f", "null", "-"],
                           capture_output=True, text=True)
        for line in r.stderr.splitlines():
            if "time=" in line:
                t = line.split("time=")[1].split(" ")[0]
                h, m, s = t.split(":")
                durations[name] = round(int(h) * 3600 + int(m) * 60 + float(s), 2)
        print(f"{name}: {durations.get(name, '?')} s")
    (OUT / "durations.json").write_text(json.dumps(durations, indent=2))
    print("total:", round(sum(durations.values()), 1), "s")


if __name__ == "__main__":
    asyncio.run(main())
