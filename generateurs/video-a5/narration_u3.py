# -*- coding: utf-8 -*-
"""Narration U3 — الجمع والطرح. Fidèle au cahier :
المجموع/الفرق · محاذاة الأرقام (كل رقم تحت خانته) · الاحتفاظ · الاستلاف · تحقق الطرح بالجمع.
Exemples du cahier : 1238+5347=6585 · 5347−1238=4109 · 509+33=542."""
import asyncio, json, subprocess
from pathlib import Path

import edge_tts
import imageio_ffmpeg

VOICE = "ar-SA-HamedNeural"
RATE = "-3%"

SEGMENTS = [
    ("intro1", "أهلًا بكم يا أبطال الرياضيات! درسُ اليوم من الوحدة الثالثة: الجمع والطرح."),
    ("intro2", "في هذا الدرس سنتعلم وضع العمليات عموديًا وإنجازها، "
               "دون أن ننسى الاحتفاظ في الجمع والاستلاف في الطرح."),
    # ── تعريف ──
    ("def1", "الجمع يعطينا المجموع، والطرح يعطينا الفرق."),
    # ── الطريقة : المحاذاة ──
    ("meth1", "وسرّ النجاح كله: المحاذاة! أكتب الأعداد بعضها تحت بعض: "
              "الآحاد تحت الآحاد، والعشرات تحت العشرات، وكل رقم تحت خانته."),
    ("meth2", "ثم أرسم خطًا تحت العدد الأخير، وأحسب انطلاقًا من الآحاد نحو اليسار."),
    # ── الجمع مع الاحتفاظ : 1238 + 5347 ──
    ("add1", "لنجمع معًا. في خانة الآحاد: ثمانية زائد سبعة يساوي خمسة عشر: "
             "أكتب خمسة، وأحتفظ بواحد فوق العشرات."),
    ("add2", "في خانة العشرات: ثلاثة زائد أربعة زائد الاحتفاظ واحد: ثمانية."),
    ("add3", "في المئات: اثنان زائد ثلاثة: خمسة. وفي الآلاف: واحد زائد خمسة: ستة."),
    ("add4", "وهكذا حصلنا على المجموع: ستة آلاف وخمسمائة وخمسة وثمانون."),
    # ── الطرح مع الاستلاف : 5347 − 1238 ──
    ("sub1", "والآن الطرح. لنطرح ألفًا ومئتين وثمانية وثلاثين من خمسة آلاف وثلاثمائة وسبعة وأربعين."),
    ("sub2", "في الآحاد: سبعة ناقص ثمانية؟ لا يمكن! أستلف واحدًا من العشرات: "
             "تصبح سبعة عشرة ناقص ثمانية: تسعة."),
    ("sub3", "في العشرات بقيت ثلاثة: ثلاثة ناقص ثلاثة: صفر. "
             "وفي المئات: ثلاثة ناقص اثنين: واحد. وفي الآلاف: خمسة ناقص واحد: أربعة."),
    ("sub4", "فالفرق هو: أربعة آلاف ومئة وتسعة."),
    # ── انتبه ──
    ("att1", "انتبه جيدًا! في الجمع لا تنسَ الاحتفاظ، وفي الطرح لا تنسَ الاستلاف."),
    # ── السر : التحقق ──
    ("astuce", "وقبل أن نفترق، إليك سرًّا ذهبيًا للتحقق من الطرح: أجمع الفرق مع المطروح. "
               "خمسمائة وتسعة زائد ثلاثة وثلاثين يساوي خمسمائة واثنين وأربعين: إذن طرحُنا صحيح!"),
    ("outro", "والآن افتح كراسك وحلّ تمارين الوحدة الثالثة. إلى اللقاء يا أبطال!"),
]

OUT = Path(__file__).parent / "audio_u3"


async def main():
    OUT.mkdir(exist_ok=True)
    ff = imageio_ffmpeg.get_ffmpeg_exe()
    durations = {}
    for name, text in SEGMENTS:
        mp3 = OUT / f"{name}.mp3"
        await edge_tts.Communicate(text, VOICE, rate=RATE).save(str(mp3))
        r = subprocess.run([ff, "-i", str(mp3), "-f", "null", "-"],
                           capture_output=True, text=True)
        for line in r.stderr.splitlines():
            if "time=" in line:
                t = line.split("time=")[1].split(" ")[0]
                h, m, s = t.split(":")
                durations[name] = round(int(h) * 3600 + int(m) * 60 + float(s), 2)
        print(f"{name}: {durations.get(name, '?')} s")
    (OUT / "durations.json").write_text(json.dumps(durations, indent=2))
    print("total:", round(sum(durations.values()), 1), "s")


if __name__ == "__main__":
    asyncio.run(main())
