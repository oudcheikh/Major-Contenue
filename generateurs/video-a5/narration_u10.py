# -*- coding: utf-8 -*-
"""Narration U10 — قياس الزوايا. Fidèle au cahier (unites_2.py u10) :
الزاوية = انفراج بين ضلعين، الرأس · القياس بالمنقلة بالدرجات ·
حادة < 90° · قائمة = 90° · منفرجة بين 90 و180 · مستقيمة = 180° · منعكسة > 180° ·
زاويتان مجموعهما 90° · المنعكسة = 360 − الزاوية الصغيرة (مثال 360−100=260)."""
import asyncio, json, subprocess
from pathlib import Path

import edge_tts
import imageio_ffmpeg

VOICE = "ar-SA-HamedNeural"
RATE = "-3%"

SEGMENTS = [
    ("intro1", "أهلًا بكم يا أبطال الرياضيات! درسُ اليوم من الوحدة العاشرة: قياس الزوايا."),
    ("intro2", "في هذا الدرس سنميّز أنواع الزوايا، وسنتعلم قياسها بالمنقلة بالدرجات، "
               "ورسم زاوية بقياس معلوم."),
    # ── التعريف ──
    ("def1", "ما هي الزاوية؟ الزاوية انفراجٌ بين ضلعين يلتقيان في نقطة تسمى الرأس."),
    ("def2", "وتقاس الزوايا بالدرجات، ونكتب الدرجة بدائرة صغيرة، وأداة القياس هي المنقلة."),
    # ── الأنواع ──
    ("typ1", "لنتعرف الأنواع: الزاوية القائمة قياسها تسعون درجة تمامًا، مثل ركن الكتاب."),
    ("typ2", "والزاوية الحادة أقل من تسعين درجة: إنها ضيقة ورفيعة."),
    ("typ3", "والزاوية المنفرجة أكبر من تسعين وأقل من مئة وثمانين: إنها واسعة."),
    ("typ4", "والزاوية المستقيمة قياسها مئة وثمانون درجة: ضلعاها على خط واحد. "
             "أما المنعكسة فأكبر من مئة وثمانين درجة."),
    # ── الطريقة : المنقلة ──
    ("meth1", "والآن كيف أقيس زاوية بالمنقلة؟ اتبعوا معي الخطوات الثلاث."),
    ("meth2", "أولًا: أضع مركز المنقلة على رأس الزاوية. "
              "ثانيًا: أُطابق أحد الضلعين مع الصفر."),
    ("meth3", "ثالثًا: أقرأ القياس عند الضلع الآخر. هذه الزاوية قياسها خمس وأربعون درجة!"),
    # ── مثال : زاويتان متكاملتان ──
    ("comp1", "لنحل مسألة من الكراس: زاويتان مجموعهما تسعون درجة، "
              "والزاوية المعلومة ست وعشرون درجة. فما قياس الأخرى؟"),
    ("comp2", "أحسب: تسعون ناقص ست وعشرين: أربع وستون درجة. هذا هو الجواب!"),
    # ── انتبه ──
    ("att1", "انتبه جيدًا! للزاوية المنعكسة سرٌّ في الحساب: "
             "أقيس الزاوية الصغيرة أولًا، ثم أطرحها من ثلاثمئة وستين درجة."),
    # ── السر ──
    ("astuce", "وقبل أن نفترق، إليك سرًّا صغيرًا: ركن كتابك زاوية قائمة جاهزة! "
               "ضعه على أي زاوية: فإن غطّتها فهي قائمة، وإن ضاقت عنها فهي حادة، "
               "وإن اتسعت فهي منفرجة."),
    ("outro", "والآن افتح كراسك وحلّ تمارين الوحدة العاشرة. إلى اللقاء يا أبطال!"),
]

OUT = Path(__file__).parent / "audio_u10"


async def main():
    OUT.mkdir(exist_ok=True)
    ff = imageio_ffmpeg.get_ffmpeg_exe()
    durations = {}
    for name, text in SEGMENTS:
        mp3 = OUT / f"{name}.mp3"
        await edge_tts.Communicate(text, VOICE, rate=RATE).save(str(mp3))
        r = subprocess.run([ff, "-i", str(mp3), "-f", "null", "-"],
                           capture_output=True, text=True)
        for line in r.stderr.splitlines():
            if "time=" in line:
                t = line.split("time=")[1].split(" ")[0]
                h, m, s = t.split(":")
                durations[name] = round(int(h) * 3600 + int(m) * 60 + float(s), 2)
        print(f"{name}: {durations.get(name, '?')} s")
    (OUT / "durations.json").write_text(json.dumps(durations, indent=2))
    print("total:", round(sum(durations.values()), 1), "s")


if __name__ == "__main__":
    asyncio.run(main())
