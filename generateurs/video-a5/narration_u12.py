# -*- coding: utf-8 -*-
"""Narration U12 — قسمة الكسور. Fidèle au cahier (unites_3.py u12) :
المقلوب = تبديل البسط والمقام · القسمة = الضرب في مقلوب الثاني · الخطوات الأربع
Exemples du cahier : 1/2 ÷ 3/4 = 1/2 × 4/3 = 4/6 = 2/3 · كم ثلثًا في وحدتين؟ 6 · كم نصفًا في 3؟ 6."""
import asyncio, json, subprocess
from pathlib import Path

import edge_tts
import imageio_ffmpeg

VOICE = "ar-SA-HamedNeural"
RATE = "-3%"

SEGMENTS = [
    ("intro1", "أهلًا بكم من جديد يا أبطال الرياضيات! درسُ اليوم من الوحدة الثانية عشرة: قسمة الكسور."),
    ("intro2", "في هذا الدرس سنتعلم إيجاد مقلوب الكسر، وقسمة كسر على كسر بالضرب في المقلوب."),
    # ── المقلوب ──
    ("maq1", "أولًا، ما هو مقلوب الكسر؟ المقلوب يعني أن نبدّل بين البسط والمقام."),
    ("maq2", "انظروا: الكسر ينقلب رأسًا على عقب! فمقلوب اثنين على ثلاثة هو ثلاثة على اثنين."),
    # ── القاعدة والخطوات ──
    ("rule1", "والآن القاعدة الذهبية: قسمة كسرين تعني ضرب الكسر الأول في مقلوب الكسر الثاني."),
    ("steps1", "الخطوات ثلاث: أُبقي الكسر الأول كما هو، وأستبدل علامة القسمة بعلامة الضرب، "
               "وأقلب الكسر الثاني."),
    # ── المثال : 1/2 ÷ 3/4 ──
    ("ex1", "لنطبّق على مثال الكراس: النصف مقسومًا على ثلاثة أرباع."),
    ("ex2", "أُبقي النصف كما هو، فتتحول القسمة إلى ضرب، وينقلب ثلاثة أرباع فيصبح أربعة على ثلاثة."),
    ("ex3", "ثم أضرب: واحد في أربعة يساوي أربعة، واثنان في ثلاثة يساوي ستة. الناتج أربعة على ستة."),
    ("ex4", "وأخيرًا أبسّط: أربعة على ستة يساوي الثلثين."),
    # ── المعنى بالرسم : كم ثلثًا في وحدتين؟ ──
    ("sens1", "ولكن، ماذا تعني القسمة على كسر؟ لنسأل السؤال: كم ثلثًا في وحدتين؟"),
    ("sens2", "أقطّع كل وحدة إلى ثلاث حصص متساوية ثم أعدّها: "
              "اثنان مقسومان على الثلث يساوي اثنين في ثلاثة: ستة أثلاث!"),
    # ── انتبه ──
    ("att1", "انتبه جيدًا! نقلب الكسر الثاني فقط، أما الكسر الأول فيبقى كما هو: "
             "قلبُ الكسر الأول أشهر خطأ في القسمة."),
    # ── السر ──
    ("astuce", "وقبل أن نفترق، إليك سرًّا صغيرًا: القسمة على النصف تعني الضرب في اثنين. "
               "كم نصفًا في ثلاث وحدات؟ ثلاثة في اثنين: ستة أنصاف!"),
    ("outro", "والآن افتح كراسك وحلّ تمارين الوحدة الثانية عشرة. إلى اللقاء يا أبطال!"),
]

OUT = Path(__file__).parent / "audio_u12"


async def main():
    OUT.mkdir(exist_ok=True)
    ff = imageio_ffmpeg.get_ffmpeg_exe()
    durations = {}
    for name, text in SEGMENTS:
        mp3 = OUT / f"{name}.mp3"
        await edge_tts.Communicate(text, VOICE, rate=RATE).save(str(mp3))
        r = subprocess.run([ff, "-i", str(mp3), "-f", "null", "-"],
                           capture_output=True, text=True)
        for line in r.stderr.splitlines():
            if "time=" in line:
                t = line.split("time=")[1].split(" ")[0]
                h, m, s = t.split(":")
                durations[name] = round(int(h) * 3600 + int(m) * 60 + float(s), 2)
        print(f"{name}: {durations.get(name, '?')} s")
    (OUT / "durations.json").write_text(json.dumps(durations, indent=2))
    print("total:", round(sum(durations.values()), 1), "s")


if __name__ == "__main__":
    asyncio.run(main())
