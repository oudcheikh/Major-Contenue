# -*- coding: utf-8 -*-
"""Narration U7 — المستقيمات المتوازية والمتقاطعة. Fidèle au cahier :
المتوازيان لا يلتقيان أبدًا ويحافظان على نفس المسافة (سكة القطار، سطور الدفتر) ·
المتقاطعان يلتقيان في نقطة واحدة (عقارب الساعة) · المتعامدان زاوية قائمة 90° ·
الرسم بالمسطرة والكوس · انتبه: ليس كل متقاطعين متعامدين."""
import asyncio, json, subprocess
from pathlib import Path

import edge_tts
import imageio_ffmpeg

VOICE = "ar-SA-HamedNeural"
RATE = "-3%"

SEGMENTS = [
    ("intro1", "أهلًا بكم يا أبطال الرياضيات! درسُ اليوم من الوحدة السابعة: "
               "المستقيمات المتوازية والمتقاطعة."),
    ("intro2", "في هذا الدرس سنتعرّف على المستقيمات المتوازية والمتقاطعة والمتعامدة، "
               "وسنجد أمثلة لها في القسم والشارع، وسنرسمها بدقة بالمسطرة والكوس."),
    # ── المتوازيان ──
    ("par1", "لنبدأ بالمستقيمين المتوازيين. أرسم مستقيمًا أول، ثم أرسم مستقيمًا ثانيًا بجانبه."),
    ("par2", "هذان المستقيمان لا يلتقيان أبدًا مهما مددناهما. "
             "انظروا: أمدّهما وأمدّهما، ولا يلتقيان!"),
    ("par3", "ويحافظان دائمًا على نفس المسافة بينهما: هنا نفس المسافة، وهناك نفس المسافة."),
    ("par4", "تمامًا مثل سكة القطار، ومثل سطور دفترك: كلها مستقيمات متوازية."),
    # ── المتقاطعان ──
    ("sec1", "والآن المستقيمان المتقاطعان: مستقيمان يلتقيان في نقطة واحدة."),
    ("sec2", "نسمّي هذه النقطة نقطة التقاطع، مثل عقربي الساعة عندما يتقاطعان."),
    # ── المتعامدان ──
    ("perp1", "وهناك حالة خاصة جميلة: إذا شكّل المستقيمان المتقاطعان زاوية قائمة، "
              "فهما متعامدان."),
    ("perp2", "نرسم مربعًا صغيرًا عند الزاوية لنقول: هذه زاوية قائمة، تسعون درجة بالضبط."),
    # ── طريقة الرسم ──
    ("draw1", "وكيف أرسم مستقيمين متوازيين؟ أرسم المستقيم الأول بالمسطرة، "
              "وأسند الكوس على المسطرة، ثم أُزلق الكوس وأرسم المستقيم الثاني."),
    # ── انتبه ──
    ("att1", "انتبه جيدًا! ليس كل متقاطعين متعامدين: "
             "التعامد يحتاج زاوية قائمة بالضبط، فتحقّق منها بالكوس."),
    # ── السر ──
    ("astuce", "وقبل أن نفترق، إليك سرًّا صغيرًا: حافتا مسطرتك متوازيتان! "
               "ارسم على طول الحافتين معًا، فتحصل على مستقيمين متوازيين بسهولة."),
    ("outro", "والآن افتح كراسك وحلّ تمارين الوحدة السابعة. إلى اللقاء يا أبطال!"),
]

OUT = Path(__file__).parent / "audio_u7"


async def main():
    OUT.mkdir(exist_ok=True)
    ff = imageio_ffmpeg.get_ffmpeg_exe()
    durations = {}
    for name, text in SEGMENTS:
        mp3 = OUT / f"{name}.mp3"
        await edge_tts.Communicate(text, VOICE, rate=RATE).save(str(mp3))
        r = subprocess.run([ff, "-i", str(mp3), "-f", "null", "-"],
                           capture_output=True, text=True)
        for line in r.stderr.splitlines():
            if "time=" in line:
                t = line.split("time=")[1].split(" ")[0]
                h, m, s = t.split(":")
                durations[name] = round(int(h) * 3600 + int(m) * 60 + float(s), 2)
        print(f"{name}: {durations.get(name, '?')} s")
    (OUT / "durations.json").write_text(json.dumps(durations, indent=2))
    print("total:", round(sum(durations.values()), 1), "s")


if __name__ == "__main__":
    asyncio.run(main())
