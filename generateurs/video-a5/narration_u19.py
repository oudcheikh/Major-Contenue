# -*- coding: utf-8 -*-
"""Narration U19 — التقاسيم غير المتساوية. Fidèle au cahier (unites_4.py u19) :
3 حالات : الفرق (أنزع الفرق، أقسم على 2، أعيده للأكبر) · المضاعف (أعدّ الحصص) ·
الكسر (أجمع أجزاء الكسر). Exemples du cahier :
سيدي وموسى 550 (فرق 210 ← 170/380) · عقد وخاتم 8800 (العقد 3 أضعاف ← 2200/6600) ·
عبد الله ومختار 2500 (2/3 ← 1000/1500) · تحقق دائمًا بالجمع."""
import asyncio, json, subprocess
from pathlib import Path

import edge_tts
import imageio_ffmpeg

VOICE = "ar-SA-HamedNeural"
RATE = "-3%"

SEGMENTS = [
    ("intro1", "أهلًا بكم يا أبطال الرياضيات! درسُ اليوم من الوحدة التاسعة عشرة: "
               "التقاسيم غير المتساوية."),
    ("intro2", "في هذا الدرس سنقسم مبلغًا بين شخصين حصتاهما غير متساويتين: "
               "بينهما فرق، أو إحداهما ضعف الأخرى، أو كسر منها."),
    # ── الحالة 1 : الفرق ──
    ("cas1", "الحالة الأولى: حصتان بينهما فرق معلوم. "
             "يملك سيدي وموسى معًا خمسمئة وخمسين أوقية، ولسيدي مئتان وعشر أوقية زيادة على موسى."),
    ("cas1b", "أرسم النموذج: شريط لموسى، وشريط مثله لسيدي، وقطعة زائدة هي الفرق."),
    ("cas1c", "أنزع الفرق أولًا: خمسمئة وخمسون ناقص مئتين وعشر: ثلاثمئة وأربعون."),
    ("cas1d", "أقسم الباقي على اثنين: حصة موسى مئة وسبعون أوقية."),
    ("cas1e", "ثم أعيد الفرق للأكبر: مئة وسبعون زائد مئتين وعشر: "
              "حصة سيدي ثلاثمئة وثمانون أوقية."),
    ("cas1f", "وأتحقق بالجمع: ثلاثمئة وثمانون زائد مئة وسبعين: "
              "خمسمئة وخمسون. حسابُنا صحيح!"),
    # ── الحالة 2 : المضاعف ──
    ("cas2", "الحالة الثانية: حصة مضاعف للأخرى. "
             "عقد وخاتم ثمنهما معًا ثمانية آلاف وثمانمئة أوقية، والعقد يساوي ثلاثة أضعاف الخاتم."),
    ("cas2b", "أعدّ الحصص: العقد ثلاث حصص والخاتم حصة واحدة: أربع حصص متساوية."),
    ("cas2c", "ثمن الخاتم: ثمانية آلاف وثمانمئة على أربعة: ألفان ومئتا أوقية. "
              "وثمن العقد: ألفان ومئتان في ثلاثة: ستة آلاف وستمئة أوقية."),
    # ── الحالة 3 : الكسر ──
    ("cas3", "الحالة الثالثة: حصة كسر من الأخرى. "
             "اقتسم عبد الله ومختار ألفين وخمسمئة أوقية، وأخذ عبد الله ثلثي حصة مختار."),
    ("cas3b", "أجمع أجزاء الكسر: لعبد الله حصتان ولمختار ثلاث: خمس حصص. "
              "الحصة الواحدة: ألفان وخمسمئة على خمسة: خمسمئة أوقية."),
    ("cas3c", "إذن حصة عبد الله ألف أوقية، وحصة مختار ألف وخمسمئة أوقية. "
              "والمجموع ألفان وخمسمئة: صحيح!"),
    # ── انتبه ──
    ("att1", "انتبه جيدًا! إذا كان بين الحصتين فرق فلا تقسم المبلغ على اثنين مباشرة: "
             "انزع الفرق أولًا ثم اقسم."),
    # ── السر ──
    ("astuce", "وقبل أن نفترق، إليك سرًّا ذهبيًا: تحقّق دائمًا في النهاية بالجمع: "
               "مجموع الحصص يجب أن يساوي المبلغ الكلي، فإن ساواه فحسابك صحيح!"),
    ("outro", "والآن افتح كراسك وحلّ تمارين الوحدة التاسعة عشرة. إلى اللقاء يا أبطال!"),
]

OUT = Path(__file__).parent / "audio_u19"


async def main():
    OUT.mkdir(exist_ok=True)
    ff = imageio_ffmpeg.get_ffmpeg_exe()
    durations = {}
    for name, text in SEGMENTS:
        mp3 = OUT / f"{name}.mp3"
        await edge_tts.Communicate(text, VOICE, rate=RATE).save(str(mp3))
        r = subprocess.run([ff, "-i", str(mp3), "-f", "null", "-"],
                           capture_output=True, text=True)
        for line in r.stderr.splitlines():
            if "time=" in line:
                t = line.split("time=")[1].split(" ")[0]
                h, m, s = t.split(":")
                durations[name] = round(int(h) * 3600 + int(m) * 60 + float(s), 2)
        print(f"{name}: {durations.get(name, '?')} s")
    (OUT / "durations.json").write_text(json.dumps(durations, indent=2))
    print("total:", round(sum(durations.values()), 1), "s")


if __name__ == "__main__":
    asyncio.run(main())
